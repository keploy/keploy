package provider

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/spf13/cobra"
	"github.com/spf13/viper"
	"go.keploy.io/server/v3/config"
	"go.keploy.io/server/v3/pkg/provenswitch"
	"go.uber.org/zap"
	"go.uber.org/zap/zaptest/observer"
)

// keploy test knows whether the bound on the app's answer is the user's own
// (config.Test.APITimeoutSet): --api-timeout, or test.apiTimeout in
// keploy.yml. keploy's own default is neither (row W1).
func TestTheAPITimeoutIsTheUsersOwnOnlyWhenTheyGaveIt(t *testing.T) {
	original := NativeCommandSupported
	t.Cleanup(func() { NativeCommandSupported = original })
	RegisterNativeCommandSupport(func(string, string) bool { return true })
	for _, tc := range []struct {
		name string
		yml  string
		args []string
		want bool
	}{
		{"keploy's default", "", nil, false},
		{"the flag", "", []string{"--api-timeout", "9"}, true},
		{"keploy.yml", "test:\n  apiTimeout: 9\n", nil, true},
		{"keploy.yml without it", "test:\n  delay: 7\n", nil, false},
		// A keploy.yml an older keploy generated holds its default 5: not
		// the user's (row W1). Another value there, or 5 in a file without
		// keploy's header, is.
		{"keploy's old generated default", "# Generated by Keploy (2-dev)\ntest:\n  apiTimeout: 5\n", nil, false},
		{"another value in a generated file", "# Generated by Keploy (2-dev)\ntest:\n  apiTimeout: 9\n", nil, true},
		{"5 in the user's own file", "test:\n  apiTimeout: 5\n", nil, true},
		{"the flag over the generated default", "# Generated by Keploy (2-dev)\ntest:\n  apiTimeout: 5\n", []string{"--api-timeout", "5"}, true},
	} {
		for _, proven := range []string{"", "1"} {
			t.Run(tc.name+" KEPLOY_PROVEN="+proven, func(t *testing.T) {
				t.Setenv(provenswitch.Env, proven)
				viper.Reset()
				t.Cleanup(viper.Reset)
				cfgDir := t.TempDir()
				if tc.yml != "" {
					file := filepath.Join(cfgDir, "keploy.yml")
					if err := os.WriteFile(file, []byte(tc.yml), 0o644); err != nil {
						t.Fatal(err)
					}
					viper.SetConfigType("yml")
					if err := viper.ReadConfig(strings.NewReader(tc.yml)); err != nil {
						t.Fatal(err)
					}
				}
				cfg := config.New()
				cfg.ConfigPath = cfgDir
				core, logs := observer.New(zap.InfoLevel)
				c := NewCmdConfigurator(zap.New(core), cfg)
				cmd := &cobra.Command{Use: "test"}
				if err := c.AddFlags(cmd); err != nil {
					t.Fatalf("AddFlags: %v", err)
				}
				dir := t.TempDir()
				if err := os.MkdirAll(filepath.Join(dir, "keploy"), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := cmd.ParseFlags(append([]string{"-c", "python app.py", "-p", dir}, tc.args...)); err != nil {
					t.Fatalf("ParseFlags: %v", err)
				}
				cfg.Command, cfg.Path = "python app.py", dir
				if err := c.ValidateFlags(context.Background(), cmd); err != nil {
					t.Fatalf("ValidateFlags: %v", err)
				}
				if cfg.Test.APITimeoutSet != tc.want {
					t.Errorf("APITimeoutSet = %v, want %v", cfg.Test.APITimeoutSet, tc.want)
				}
				// Under the switch keploy says, once, that it takes the
				// generated default for none of the user's, and how to keep a
				// bound.
				said := logs.FilterMessageSnippet("is the default an older keploy wrote into it").All()
				wantSaid := 0
				if proven == "1" && tc.name == "keploy's old generated default" {
					wantSaid = 1
				}
				if len(said) != wantSaid {
					t.Fatalf("the generated default was said %d times, want %d", len(said), wantSaid)
				}
				if wantSaid == 1 && (!strings.Contains(said[0].Message, "--api-timeout") || !strings.Contains(said[0].Message, filepath.Join(cfgDir, "keploy.yml"))) {
					t.Fatalf("the notice does not say how to keep a bound: %q", said[0].Message)
				}
			})
		}
	}
}
