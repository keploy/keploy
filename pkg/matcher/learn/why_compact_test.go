func TestCompactWhyRoundTripsThroughHeaderForEveryKind(t *testing.T) {
	valLine := compactLearnedLine(learnedWord{
		Test:     ".::TestCreate",
		Mock:     "mock-4536",
		Field:    "body.cmd.filter._id",
		Word:     0,
		Recorded: "6a7f20f8",
		Full:     "6c8db4e9",
		Outcome:  OutcomeValue,
		Rule:     "bound to mock-4535 body.cmd.filter.appId" + defaultValueRuleSuffix,
		Places:   []string{"mock-4535 body.cmd.filter.appId"},
	})
	freshLine := compactLearnedLine(learnedWord{
		Test:     ".::TestCreate",
		Mock:     "mock-4535",
		Field:    "body.cmd.filter.appId",
		Word:     0,
		Recorded: "6a7f20f8",
		Full:     "6c8db4e9",
		Outcome:  OutcomeFresh,
		Rule:     defaultFreshRule,
	})
	clockLine := compactLearnedLine(learnedWord{
		Test:     ".::TestCreate",
		Mock:     "mock-4540",
		Field:    "header.X-Timestamp",
		Word:     -1,
		Recorded: "1700000001",
		Full:     "1700000002",
		Outcome:  OutcomeClock,
		Rule:     "clock +/- 2s",
	})
	carriedLine := CompactCarriedWhy(".::TestCreate", "mock-4752 body.docs.msgs.0.id#0")
	carriedBindLine := CompactCarriedBindWhy(".::TestCreate", "mock-4752 body.docs.msgs.0.id#0")
	answeredLine := CompactAnsweredWhy("body.cursor.firstBatch.0.appId#0", "6a7f20f8", "6c8db4e9", "mock-4535 body.cmd.filter.appId#0", "what this test wrote")

	vars := models.MockVariables{
		"v1": {Why: valLine},
		"v2": {Why: freshLine},
		"v3": {Why: clockLine},
		"v4": {Why: carriedLine},
		"v5": {Why: carriedBindLine},
		"v6": {Why: answeredLine},
	}
	kinds := WhyKindsInVars(vars)
	hdrText := FormatWhyHeader(kinds)
	if hdrText == "" {
		t.Fatal("FormatWhyHeader returned empty string for non-empty kinds")
	}
	parsed := ParseWhyHeader([]byte("# Generated by Keploy (3-dev)\n" + hdrText + "version: api.keploy.io/v1beta1\n"))

	// Value: resolves full what, rule with source, and exact requestbody undo.
	rv, ok := ResolveWhy(parsed, valLine)
	if !ok {
		t.Fatalf("ResolveWhy failed on value line %q", valLine)
	}
	if rv.Kind != WhyKindValue || !strings.Contains(rv.What, "bound at its source") {
		t.Fatalf("value resolved unexpected what: %+v", rv)
	}
	if !strings.Contains(rv.Rule, "mock-4535 body.cmd.filter.appId") {
		t.Fatalf("value resolved rule %q does not name bind source", rv.Rule)
	}
	if !strings.Contains(rv.Undo, `test.globalNoise.global.requestbody: {"cmd.filter._id": []}`) {
		t.Fatalf("value resolved undo %q does not give exact keploy.yml edit", rv.Undo)
	}
	if rv.Fields["rec"] != "6a7f20f8" || rv.Fields["full"] != "6c8db4e9" || rv.Fields["at"] != "body.cmd.filter._id#0" {
		t.Fatalf("value fields lost evidence: %+v", rv.Fields)
	}

	// Fresh: resolves default rule and exact undo.
	rf, ok := ResolveWhy(parsed, freshLine)
	if !ok || rf.Kind != WhyKindFresh || !strings.Contains(rf.Rule, "no place before the call shows it") ||
		!strings.Contains(rf.Undo, `test.globalNoise.global.requestbody: {"cmd.filter.appId": []}`) {
		t.Fatalf("fresh resolved unexpectedly: ok=%v %+v", ok, rf)
	}

	// Clock: resolves header undo and custom rule.
	rc, ok := ResolveWhy(parsed, clockLine)
	if !ok || rc.Kind != WhyKindClock || rc.Rule != "clock +/- 2s" ||
		!strings.Contains(rc.Undo, `test.globalNoise.global.header: {"X-Timestamp": []}`) {
		t.Fatalf("clock resolved unexpectedly: ok=%v %+v", ok, rc)
	}

	// Carried: resolves source, test, and exact delete undo.
	rcar, ok := ResolveWhy(parsed, carriedLine)
	if !ok || rcar.Kind != WhyKindCarried ||
		!strings.Contains(rcar.Rule, "mock-4752 body.docs.msgs.0.id#0") ||
		!strings.Contains(rcar.Rule, ".::TestCreate") ||
		rcar.Undo != "delete this variable from this mock" {
		t.Fatalf("carried resolved unexpectedly: ok=%v %+v", ok, rcar)
	}

	// Carried-bind and answered.
	rcb, ok := ResolveWhy(parsed, carriedBindLine)
	if !ok || rcb.Kind != WhyKindCarriedBind || !strings.Contains(rcb.Rule, "mock-4752 body.docs.msgs.0.id#0") {
		t.Fatalf("carried-bind resolved unexpectedly: ok=%v %+v", ok, rcb)
	}
	ra, ok := ResolveWhy(parsed, answeredLine)
	if !ok || ra.Kind != WhyKindAnswered || !strings.Contains(ra.Rule, "mock-4535 body.cmd.filter.appId#0") || ra.Undo != "re-record" {
		t.Fatalf("answered resolved unexpectedly: ok=%v %+v", ok, ra)
	}

	// Missing kind in header fails closed.
	if _, ok := ResolveWhy(map[string]WhyKindDoc{}, valLine); ok {
		t.Fatal("ResolveWhy must return ok=false when header lacks the line's kind")
	}
}

func TestCompactWhyMasksSecretsAndHandlesReRecordUndo(t *testing.T) {
	sec := compactLearnedLine(learnedWord{
		Test:     ".::TestAuth",
		Mock:     "mock-9",
		Field:    "header.Authorization",
		Word:     1,
		Recorded: "secret-tok-1",
		Full:     "secret-tok-2",
		Outcome:  OutcomeFresh,
		Rule:     `bound to "secret-tok-1"`,
	})
	if strings.Contains(sec, "secret-tok-1") || strings.Contains(sec, "secret-tok-2") {
		t.Fatalf("compact why leaked secret values: %s", sec)
	}
	if !strings.Contains(sec, `rec="***" full="***"`) {
		t.Fatalf("compact why did not mask secret values: %s", sec)
	}

	// A field with no keploy.yml noise bucket resolves undo to re-record.
	noNoise := compactLearnedLine(learnedWord{
		Test:     ".::TestSQL",
		Mock:     "mock-2",
		Field:    "param.1",
		Word:     -1,
		Recorded: "abc",
		Full:     "def",
		Outcome:  OutcomeFresh,
		Rule:     defaultFreshRule,
	})
	hdr := ParseWhyHeader([]byte(FormatWhyHeader([]string{WhyKindFresh})))
	res, ok := ResolveWhy(hdr, noNoise)
	if !ok || res.Undo != "re-record" {
		t.Fatalf("expected re-record undo for param.1, got ok=%v %+v", ok, res)
	}
}

func TestCompactWhyShrinksRecordedLinesSignificantly(t *testing.T) {
	lw := learnedWord{
		Test:     ".::TestTestRunReportOnClient",
		Mock:     "mock-4536",
		Field:    "body.cmd.filter._id",
		Word:     0,
		Recorded: "6a7f20f8",
		Full:     "6c8db4e9",
		Outcome:  OutcomeValue,
		Rule:     "bound to mock-4535 body.cmd.filter.appId" + defaultValueRuleSuffix,
		Places:   []string{"mock-4535 body.cmd.filter.appId"},
	}
	verbose := learnedLine(lw)
	compact := compactLearnedLine(lw)
	if len(compact)*2 >= len(verbose) {
		t.Fatalf("compact line (%d B) did not shrink verbose line (%d B) by at least 2x:\nverbose: %s\ncompact: %s", len(compact), len(verbose), verbose, compact)
	}
}

func TestWhyKindsInYAMLAndStripHeaderAreIdempotent(t *testing.T) {
	doc := []byte("version: api.keploy.io/v1beta1\nkind: Mongo\nname: mock-1\nvariables:\n    id0:\n        recorded: 6a7f20f8\n        why: '[value] test=\".::TestA\" at=\"body.id#0\" rec=\"a\" full=\"b\" from=\"mock-0 body.id\" undo=\"requestbody:id\"'\n    c0:\n        recorded: 4b50\n        why: '[carried] test=\".::TestA\" from=\"mock-0 body.k#0\"'\n")
	kinds := WhyKindsInYAML(doc)
	if strings.Join(kinds, ",") != "carried,value" {
		t.Fatalf("WhyKindsInYAML = %v, want [carried value]", kinds)
	}
	withHdr := append([]byte("# Generated by Keploy (3-dev)\n"+FormatWhyHeader(kinds)), doc...)
	stripped := StripWhyHeader(withHdr)
	if strings.Contains(string(stripped), WhyHeaderStart) {
		t.Fatalf("StripWhyHeader left header behind:\n%s", stripped)
	}
	if !strings.HasPrefix(string(stripped), "# Generated by Keploy (3-dev)\nversion: ") {
		t.Fatalf("StripWhyHeader corrupted non-header comments:\n%s", stripped)
	}
}

func TestDecidePopulatesCompactLineResolvableThroughHeader(t *testing.T) {
	ds := Decide(oInput("body.cmd.filter.appId", "6a7f20f8-1111-2222-3333-444455556666", "6c8db4e9-1111-2222-3333-444455556666", nil, nil))
	if len(ds) != 1 || ds[0].Outcome != OutcomeFresh {
		t.Fatalf("unexpected Decide output: %+v", ds)
	}
	got := CompactLine(ds[0])
	if !strings.HasPrefix(got, "["+WhyKindFresh+"] ") || got == ds[0].Line {
		t.Fatalf("CompactLine(d) = %q (Line=%q); want compact [fresh] line", got, ds[0].Line)
	}
	hdr := ParseWhyHeader([]byte(FormatWhyHeader([]string{WhyKindFresh})))
	res, ok := ResolveWhy(hdr, got)
	if !ok || res.Kind != WhyKindFresh || !strings.Contains(res.Rule, "no place before the call shows it") ||
		!strings.Contains(res.Undo, `test.globalNoise.global.requestbody: {"cmd.filter.appId": []}`) {
		t.Fatalf("CompactLine(d) did not resolve through header: ok=%v %+v", ok, res)
	}
	if fb := CompactLine(Decision{Line: "fallback line"}); fb != "fallback line" {
		t.Fatalf("CompactLine fallback = %q, want fallback line", fb)
	}
}
