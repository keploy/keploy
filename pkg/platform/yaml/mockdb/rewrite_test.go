// Cutting any document of a real recording, as the file's last, at any point
// inside a line never fails the set and never serves a changed mock: every
// mock read is the recorded one, byte for byte, and the cut one is skipped
// with one WARN. A cut inside the separator before a document, or after all of
// it but its newline, leaves the one before it whole and read, with no WARN;
// so does an NDJSON line cut only of its newline. (A cut at a line boundary
// leaves a file that ends with a newline, which is read as it always was.)
//
// The last document is cut at every position, the others at every 11th, to
// keep the suite fast; KEPLOY_CUT_SWEEP_STRIDE=1 cuts every document at every
// position (about 22,000 cuts in YAML).
func TestCuttingAnyDocumentNeverServesAChangedMock(t *testing.T) {
	for _, format := range []string{"yaml", "json"} {
		t.Run(format, func(t *testing.T) {
			dir := t.TempDir()
			core, logs := observer.New(zapcore.WarnLevel)
			ys := NewWithFormat(zap.New(core), dir, "mocks", formatOf(format))
			sweepCuts(t, dir, format, func(c cutCase) {
				t.Helper()
				logs.TakeAll()
				set, err := ys.GetTestSetMocks(context.Background(), pruneSet, models.BaseTime, time.Now(), nil, nil)
				if err != nil {
					t.Fatalf("%s: the set failed: %v", c.what, err)
				}
				got := append(append([]*models.Mock(nil), set.AllPerTest...), set.AllSession...)
				sameMocks(t, c.what, got, c.recorded)
				if names := sortedNames(got); !slices.Equal(names, c.served) {
					t.Fatalf("%s: served %v, want %v", c.what, names, c.served)
				}
				want := 0
				if c.warn {
					want = 1
				}
				if n := len(incompleteWarnings(logs)); n != want {
					t.Fatalf("%s: %d incomplete WARNs, want %d; logs %v", c.what, n, want, logs.All())
				}
				if loud := logs.FilterLevelExact(zapcore.ErrorLevel).All(); len(loud) != 0 {
					t.Fatalf("%s: a cut is not an error: %v", c.what, loud)
				}
			})
		})
	}
}

// cutCase is one cut of sweepCuts: a mock file that ends part-way through a
// line.
type cutCase struct {
	what string
	// file is the cut file.
	file string
	// recorded is every mock of the file before the cut, encoded, by name.
	recorded map[string][]byte
	// served is the names, sorted, of the mocks the read serves.
	served []string
	// warn says the read skips the cut mock, with one WARN.
	warn bool
}

// sweepCuts writes, to the set in dir, every cut of a real recording in
// format and calls visit with each: each document as the file's last (after
// the one before it), cut at every point inside a line (the last document) or
// every stride-th (the others, KEPLOY_CUT_SWEEP_STRIDE, 11 by default), inside
// or at the end of the separator before it (YAML), and only of its newline
// (NDJSON).
func sweepCuts(t *testing.T, dir, format string, visit func(c cutCase)) {
	t.Helper()
	stride := 11
	if v, err := strconv.Atoi(os.Getenv("KEPLOY_CUT_SWEEP_STRIDE")); err == nil && v > 0 {
		stride = v
	}
	src, err := os.ReadFile(filepath.Join("testdata", "no_connfailure_golden", "recorded."+format))
	if err != nil {
		t.Fatal(err)
	}
	var header string
	var docs []string
	if format == "json" {
		docs = strings.Split(strings.TrimSuffix(string(src), "\n"), "\n")
	} else {
		body := string(src)
		for strings.HasPrefix(body, "#") {
			nl := strings.Index(body, "\n") + 1
			header += body[:nl]
			body = body[nl:]
		}
		docs = strings.Split(strings.TrimPrefix(body, "---\n"), "\n---\n")
		for i := range docs[:len(docs)-1] {
			docs[i] += "\n"
		}
	}
	if len(docs) < 10 {
		t.Fatalf("precondition: a recording of every kind, got %d documents", len(docs))
	}
	path := filepath.Join(dir, pruneSet, "mocks."+format)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("KEPLOY_MOCK_FORMAT", "")
	ys := NewWithFormat(zap.NewNop(), dir, "mocks", formatOf(format))
	write := func(b string) {
		if err := os.WriteFile(path, []byte(b), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	read := func(b string) []*models.Mock {
		write(b)
		set, err := ys.GetTestSetMocks(context.Background(), pruneSet, models.BaseTime, time.Now(), nil, nil)
		if err != nil {
			t.Fatal(err)
		}
		return append(append([]*models.Mock(nil), set.AllPerTest...), set.AllSession...)
	}
	cuts := 0
	for k := range docs {
		// The file: the document before (if any), then this one.
		prefix := header
		sep := ""
		if k > 0 {
			prefix += docs[k-1]
			sep = "---\n"
			if format == "json" {
				prefix, sep = docs[k-1]+"\n", ""
			}
		}
		whole := prefix + sep + docs[k]
		if format == "json" {
			whole += "\n"
		}
		recorded := map[string][]byte{}
		for _, m := range read(whole) {
			recorded[m.Name] = encodeForCompare(t, m)
		}
		var before []string
		if prefix != "" {
			before = sortedNames(read(prefix))
		}
		withCut := sortedNames(read(whole))
		if len(withCut) != len(before)+1 {
			t.Fatalf("precondition: document %d is one mock, got %v after %v", k, withCut, before)
		}
		cut := func(file string, warn, cutServed bool) {
			t.Helper()
			cuts++
			c := cutCase{what: fmt.Sprintf("document %d cut to %q", k, file[max(0, len(file)-40):]), file: file, recorded: recorded, served: before, warn: warn}
			if cutServed {
				c.served = withCut
			}
			write(file)
			visit(c)
		}
		step := stride
		if k == len(docs)-1 {
			step = 1
		}
		last := len(whole)
		if format == "json" {
			// The whole line without its newline is a whole object.
			last = len(whole) - 1
			cut(whole[:last], false, true)
		}
		for end := len(prefix) + len(sep) + 1; end < last; end += step {
			if whole[end-1] == '\n' {
				continue
			}
			cut(whole[:end], true, false)
		}
		if format == "yaml" && k > 0 {
			for _, s := range []string{"-", "--", "---", "--- "} {
				cut(prefix+s, false, false)
			}
		}
	}
	if cuts < 500 {
		t.Fatalf("precondition: want a real recording to cut, cut it %d times", cuts)
	}
	t.Logf("%d cuts", cuts)
}

func sortedNames(mocks []*models.Mock) []string {
	names := make([]string, 0, len(mocks))
	for _, m := range mocks {
		names = append(names, m.Name)
	}
	slices.Sort(names)
	return names
}

