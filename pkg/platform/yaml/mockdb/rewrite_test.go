// Documents this keploy cannot decode: a kind with a hyphen (enterprise-only,
// skipped at Debug), a kind it has never heard of (written by a newer keploy,
// skipped with an ERROR), and a connection failure with an outcome it does not
// support (likewise). The odd spacing, the key order and the YAML comment are
// there so that a rewrite which re-encoded the document instead of copying it
// would be caught: only a byte-for-byte copy keeps them.
var (
	undecodableYAMLConnFailure = cfDocYAML("cf-newer", "request", "reset", true)
	undecodableJSONConnFailure = cfDocJSON("cf-newer", "request", "reset", true)
)

const (
	undecodableYAMLEnterprise = "version: api.keploy.io/v1beta1\nkind: Acme-Queue\nname: mock-acme\nspec:\n    metadata:\n        type:   mocks   # spacing and this comment survive only a verbatim copy\n    reqTimestampMock: 2026-01-02T03:04:05Z\n"
	undecodableYAMLFuture     = "kind: FutureKind\nversion: api.keploy.io/v1beta1\nname: mock-future\nspec: {address: \"10.0.0.9:443\", answer: [1, 2]}\n"
	undecodableJSONEnterprise = `{"kind":"Acme-Queue", "version":"api.keploy.io/v1beta1","name":"mock-acme","spec":{"metadata":{"type":"mocks"}}}`
	undecodableJSONFuture     = `{"version":"api.keploy.io/v1beta1","kind":"FutureKind","name":"mock-future","spec":{"answer":[1,2],  "address":"10.0.0.9:443"}}`
)

// rewriteFixture records the mixed prune fixture with the two undecodable
// documents in the middle of it, and returns the mock file's path.
func rewriteFixture(t *testing.T, dir, format string) string {
	t.Helper()
	return writePruneFixture(t, dir, format, pruneMixedFixture(), undecodableRaw(format))
}

// undecodableRaw is every undecodable document of the format, as appended to
// a mock file.
func undecodableRaw(format string) string {
	if format == "json" {
		return undecodableJSONEnterprise + "\n" + undecodableJSONFuture + "\n" + undecodableJSONConnFailure + "\n"
	}
	return "---\n" + undecodableYAMLEnterprise + "---\n" + undecodableYAMLFuture + "---\n" + undecodableYAMLConnFailure
}

// assertKeptVerbatim fails unless every undecodable document of the format is
// still in the file at path, byte for byte, as a document of its own.
func assertKeptVerbatim(t *testing.T, path, format string) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the rewritten mock file: %v", err)
	}
	got := string(data)
	if format == "json" {
		lines := map[string]int{}
		for _, l := range strings.Split(got, "\n") {
			lines[l]++
		}
		for _, want := range []string{undecodableJSONEnterprise, undecodableJSONFuture, undecodableJSONConnFailure} {
			if lines[want] != 1 {
				t.Fatalf("the rewrite did not keep a document it cannot decode as the same line, exactly once (found %d).\nwant line: %s\nfile:\n%s", lines[want], want, got)
			}
		}
		return
	}
	docs := map[string]int{}
	for _, d := range yamlDocuments(got) {
		docs[d]++
	}
	for _, want := range []string{undecodableYAMLEnterprise, undecodableYAMLFuture, undecodableYAMLConnFailure} {
		if docs[want] != 1 {
			t.Fatalf("the rewrite did not keep a document it cannot decode, byte for byte, as a document of its own exactly once (found %d).\nwant document:\n%s\nfile:\n%s", docs[want], want, got)
		}
	}
}

// yamlDocuments splits a mocks.yaml the way keploy's reader does: documents
// are separated by "---" lines, and comment lines before the first document's
// content (the "# Generated by Keploy" header) belong to no document.
func yamlDocuments(s string) []string {
	var docs []string
	var cur strings.Builder
	first := true
	for _, line := range strings.SplitAfter(s, "\n") {
		if line == "" {
			continue
		}
		if strings.TrimSpace(line) == "---" {
			if cur.Len() > 0 {
				docs = append(docs, cur.String())
				cur.Reset()
			}
			first = false
			continue
		}
		if first && cur.Len() == 0 && strings.HasPrefix(line, "#") {
			continue
		}
		cur.WriteString(line)
	}
	if cur.Len() > 0 {
		docs = append(docs, cur.String())
	}
	return docs
}

// decodableNames lists the mocks this keploy reads back from the file, which
// must still parse whole after the rewrite.
func decodableNames(t *testing.T, dir, format string) []string {
	t.Helper()
	f := yaml.FormatYAML
	if format == "json" {
		f = yaml.FormatJSON
	}
	ys := NewWithFormat(zap.NewNop(), dir, "mocks", f)
	set, err := ys.GetTestSetMocks(context.Background(), pruneSet, models.BaseTime, time.Now(), nil, nil)
	if err != nil {
		t.Fatalf("read the rewritten file back: %v", err)
	}
	var names []string
	for _, m := range append(set.AllPerTest, set.AllSession...) {
		names = append(names, m.Name)
	}
	return names
}

// A prune drops the mocks no test consumed and rewrites the rest. A document
// it cannot decode is not one it can judge, so it must be copied through
// untouched: dropping it deletes, from the user's recording, mocks that a
// newer keploy (or keploy enterprise) wrote and would have replayed.
func TestUpdateMocks_KeepsADocumentItCannotDecodeVerbatim(t *testing.T) {
	consumed, pruneBefore, startupCutoff := pruneMixedArgs()
	for _, format := range []string{"yaml", "json"} {
		t.Run(format, func(t *testing.T) {
			dir := t.TempDir()
			path := rewriteFixture(t, dir, format)
			before := len(decodableNames(t, dir, format))

			f := yaml.FormatYAML
			if format == "json" {
				f = yaml.FormatJSON
			}
			ys := NewWithFormat(zap.NewNop(), dir, "mocks", f)
			if err := ys.UpdateMocks(context.Background(), pruneSet, consumed, pruneBefore, startupCutoff); err != nil {
				t.Fatalf("UpdateMocks: %v", err)
			}

			assertKeptVerbatim(t, path, format)
			if after := len(decodableNames(t, dir, format)); after == 0 || after >= before {
				t.Fatalf("the prune must still prune the mocks it can judge: %d decodable mocks before, %d after", before, after)
			}
		})
	}
}

