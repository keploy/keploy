// A rewrite (the prune, the noise write-back) of a file whose last mock the
// read skipped, because it does not end with a newline (cut short by an
// interrupted write, or saved by hand without its final newline), does not
// copy that mock: it moves it, byte for byte, to <file>.incomplete-<nanos>
// beside the file, with one WARN naming both, and the rewritten file ends with
// a newline. A file that stops in the separator after its last whole mock
// ("--") is rewritten without the dashes, and an NDJSON line the read took
// gets its newline. Either way a mock appended afterwards starts on a line of
// its own, and the set then reads every recorded mock but the skipped one,
// unchanged, and the appended one, with no WARN. (Copied as it was, an
// unfinished line would join the appended mock: the set stopped loading, or,
// when the cut fell in a line's indentation, read the separator after it and
// served the cut mock without its later fields.)
func TestARewriteMovesAnIncompleteLastMockAside(t *testing.T) {
	cases := []struct {
		name, format string
		// end damages the whole file data and returns where the moved-aside
		// mock starts (-1: nothing is moved aside).
		end func(data []byte) ([]byte, int)
	}{
		{"cut in a line's indentation", "yaml", func(d []byte) ([]byte, int) {
			at := bytes.LastIndex(d, []byte("\n    ")) + 5
			return d[:at], bytes.LastIndex(d[:at], []byte("\n---\n")) + 5
		}},
		{"cut mid-token", "yaml", func(d []byte) ([]byte, int) {
			at := bytes.LastIndex(d, []byte("resTimestampMock: ")) + len("resTimestampMock: ") + 7
			return d[:at], bytes.LastIndex(d[:at], []byte("\n---\n")) + 5
		}},
		{"a whole last line without its newline", "yaml", func(d []byte) ([]byte, int) {
			d = bytes.TrimSuffix(d, []byte("\n"))
			return d, bytes.LastIndex(d, []byte("\n---\n")) + 5
		}},
		{"-- after the last mock", "yaml", func(d []byte) ([]byte, int) {
			return append(append([]byte(nil), d...), "--"...), -1
		}},
		{"-- after a mock copied as written", "yaml", func(d []byte) ([]byte, int) {
			return append(append(append([]byte(nil), d...), "---\n"+undecodableYAMLEnterprise...), "--"...), -1
		}},
		{"cut mid-token", "json", func(d []byte) ([]byte, int) {
			at := bytes.LastIndex(d, []byte(`"resTimestampMock":"`)) + len(`"resTimestampMock":"`) + 7
			return d[:at], bytes.LastIndexByte(d[:at], '\n') + 1
		}},
		{"a whole last line without its newline", "json", func(d []byte) ([]byte, int) {
			return bytes.TrimSuffix(d, []byte("\n")), -1
		}},
	}
	for _, c := range cases {
		for _, rewrite := range []string{"prune", "noise"} {
			t.Run(c.format+"/"+c.name+"/"+rewrite+", append", func(t *testing.T) {
				dir := t.TempDir()
				path := writePruneFixture(t, dir, c.format, []*models.Mock{pruneHTTPMock(1), pruneHTTPMock(2), pruneHTTPMock(3)}, "")
				_, whole, _, err := readAllMocks(t, dir, c.format)
				if err != nil {
					t.Fatal(err)
				}
				recorded := map[string][]byte{}
				for _, m := range whole {
					recorded[m.Name] = encodeForCompare(t, m)
				}
				data, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				damaged, asideFrom := c.end(data)
				if err := os.WriteFile(path, damaged, 0o644); err != nil {
					t.Fatal(err)
				}
				want := []string{"mock-0", "mock-1", "mock-11", "mock-2"}
				if asideFrom >= 0 {
					want = []string{"mock-0", "mock-1", "mock-11"}
					delete(recorded, "mock-2")
				}

				core, logs := observer.New(zapcore.DebugLevel)
				ys := NewWithFormat(zap.New(core), dir, "mocks", formatOf(c.format))
				switch rewrite {
				case "prune":
					consumed := map[string]models.MockState{"mock-0": {Name: "mock-0"}, "mock-1": {Name: "mock-1"}, "mock-2": {Name: "mock-2"}}
					if err := ys.UpdateMocks(context.Background(), pruneSet, consumed, pruneT0.Add(time.Hour), time.Time{}); err != nil {
						t.Fatalf("UpdateMocks: %v", err)
					}
				case "noise":
					states := map[string]models.MockState{"mock-0": {Name: "mock-0", ReqBodyNoise: map[string][]string{"body.request_id": {}}}}
					if err := ys.PersistMockNoise(context.Background(), pruneSet, states); err != nil {
						t.Fatalf("PersistMockNoise: %v", err)
					}
					delete(recorded, "mock-0") // it carries the learned noise now
				}
				after, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				if !bytes.HasSuffix(after, []byte("\n")) || bytes.HasSuffix(after, []byte("--\n")) {
					t.Fatalf("the rewritten file must end with a newline, after a whole mock; it ends %q", after[max(0, len(after)-40):])
				}
				asides, _ := filepath.Glob(path + ".incomplete-*")
				moved := logs.FilterMessageSnippet("the rewrite moved it aside").All()
				if asideFrom < 0 {
					if len(asides) != 0 || len(moved) != 0 {
						t.Fatalf("the read skipped nothing, so nothing is moved aside: %v, %v", asides, moved)
					}
				} else {
					if len(asides) != 1 {
						t.Fatalf("want the skipped mock moved aside to one file, got %v", asides)
					}
					if got, _ := os.ReadFile(asides[0]); !bytes.Equal(got, damaged[asideFrom:]) {
						t.Fatalf("moved aside %q, want the skipped mock as it was, %q", got, damaged[asideFrom:])
					}
					if bytes.Contains(after, damaged[asideFrom:]) {
						t.Fatal("the skipped mock is still in the rewritten file")
					}
					if len(moved) != 1 || moved[0].Level != zapcore.WarnLevel || moved[0].ContextMap()["mock_file"] != path || moved[0].ContextMap()["moved_to"] != asides[0] {
						t.Fatalf("want one WARN naming %s and %s, got %v", path, asides[0], moved)
					}
				}

				ys.SetCounterID(10)
				if err := ys.InsertMock(context.Background(), pruneHTTPMock(4), pruneSet); err != nil {
					t.Fatalf("InsertMock: %v", err)
				}
				_, got, rlogs, err := readAllMocks(t, dir, c.format)
				if err != nil {
					t.Fatalf("the set stopped loading after the append: %v", err)
				}
				if w := rlogs.FilterLevelExact(zapcore.WarnLevel).All(); len(w) != 0 {
					t.Fatalf("the file reads whole after the append: %v", w)
				}
				if names := sortedNames(got); !slices.Equal(names, want) {
					t.Fatalf("served %v, want %v", names, want)
				}
				var unchanged []*models.Mock
				for _, m := range got {
					if _, ok := recorded[m.Name]; ok {
						unchanged = append(unchanged, m)
					}
				}
				sameMocks(t, "after the rewrite and an append", unchanged, recorded)
			})
		}
	}
}

