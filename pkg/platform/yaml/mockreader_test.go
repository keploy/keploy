// TestMockReaderIndentedSeparatorInsideBlockScalar guards the regression where
// an indented "---" inside a recorded body was treated as a document
// separator.
//
// A YAML document separator only separates at column 0. The reader used to
// anchor its check with strings.TrimSpace, which strips leading whitespace too,
// so a body containing markdown / YAML / front matter split the document
// mid-scalar. keploy then could not read back a mocks.yaml it had written
// itself, and the whole test set failed to load rather than a single mock.
//
// Recording an LLM-backed flow hits this immediately, because "---" is
// ubiquitous in prompts.
func TestMockReaderIndentedSeparatorInsideBlockScalar(t *testing.T) {
	ctx := context.Background()
	logger := getTestLogger()

	tempDir, err := os.MkdirTemp("", "mockreader_indented_sep_test")
	if err != nil {
		t.Fatalf("Failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tempDir)

	// Two documents. The FIRST carries a block scalar whose content contains
	// indented "---" lines; only the column-0 "---" is a real separator.
	content := `# Generated by Keploy
---
version: api.keploy.io/v1beta1
kind: Http
name: mock-1
spec:
    metadata:
        operation: prompt
    req:
        method: POST
        url: /v1/responses
        body: |+
            Some prompt text.
            ---
            A section after an indented separator.
            ---
            key: value
    res:
        status_code: 200
---
version: api.keploy.io/v1beta1
kind: Http
name: mock-2
spec:
    metadata:
        operation: second
    req:
        method: GET
        url: /healthz
    res:
        status_code: 200
`

	if err := os.WriteFile(filepath.Join(tempDir, "mocks.yaml"), []byte(content), 0644); err != nil {
		t.Fatalf("Failed to write mock file: %v", err)
	}

	reader, err := NewMockReader(ctx, logger, tempDir, "mocks")
	if err != nil {
		t.Fatalf("Failed to create mock reader: %v", err)
	}
	defer func() { _ = reader.Close() }()

	var names []string
	for {
		doc, err := reader.ReadNextDoc()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatalf("ReadNextDoc failed (the indented \"---\" was treated as a separator): %v", err)
		}
		names = append(names, doc.Name)
	}

	if len(names) != 2 {
		t.Fatalf("expected 2 documents, got %d (%v)", len(names), names)
	}
	if names[0] != "mock-1" || names[1] != "mock-2" {
		t.Fatalf("expected [mock-1 mock-2], got %v", names)
	}
}

// TestMockReaderSeparatorWithTrailingWhitespace keeps a column-0 "---" that has
// trailing spaces working as a separator -- the fix must only stop trimming the
// LEADING side.
func TestMockReaderSeparatorWithTrailingWhitespace(t *testing.T) {
	ctx := context.Background()
	logger := getTestLogger()

	tempDir, err := os.MkdirTemp("", "mockreader_trailing_ws_test")
	if err != nil {
		t.Fatalf("Failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tempDir)

	content := "---   \n" +
		"version: api.keploy.io/v1beta1\n" +
		"kind: Http\n" +
		"name: mock-1\n" +
		"spec:\n" +
		"    metadata:\n" +
		"        operation: first\n" +
		"---\t\n" +
		"version: api.keploy.io/v1beta1\n" +
		"kind: Http\n" +
		"name: mock-2\n" +
		"spec:\n" +
		"    metadata:\n" +
		"        operation: second\n"

	if err := os.WriteFile(filepath.Join(tempDir, "mocks.yaml"), []byte(content), 0644); err != nil {
		t.Fatalf("Failed to write mock file: %v", err)
	}

	reader, err := NewMockReader(ctx, logger, tempDir, "mocks")
	if err != nil {
		t.Fatalf("Failed to create mock reader: %v", err)
	}
	defer func() { _ = reader.Close() }()

	count := 0
	for {
		_, err := reader.ReadNextDoc()
		if err == io.EOF {
			break
		}
		if err != nil {
			t.Fatalf("ReadNextDoc failed: %v", err)
		}
		count++
	}

	if count != 2 {
		t.Fatalf("expected 2 documents, got %d", count)
	}
}
