// Backward-compatibility pin for the consumer contract.
//
// Adding models.CONSUMER touches four switches in util.go, one in naming.go
// and two in db.go, every one of them by INSERTING an arm before an existing
// default. The claim that no existing kind changed is only worth anything if
// something checks it, so these fixtures are encoded through the real
// EncodeTestcase / EncodeTestcaseJSON and compared byte-for-byte against files
// GENERATED BY THE PRE-CONSUMER BUILD (commit 8181969). Regenerating them from
// the post-change code would make the test vacuous, which is why the update
// flag exists but the checked-in bytes came from the old tree.
//
// The four files this test reads — http-testcase.{yaml,json} and
// grpc-testcase.{yaml,json} — are the ONLY compatibility goldens in that
// directory. testdata/consumer-testcase.{yaml,json} could not be generated by
// the pre-consumer build because they describe a schema that did not exist
// there; they are a forward schema pin owned by TestConsumerTestCaseSchemaIsPinned
// in consumer_test.go, and they prove nothing about backward compatibility.
//
// To regenerate deliberately (only when a schema change is intended and
// reviewed):
//
//	go test ./pkg/platform/yaml/testdb/... -run TestExistingKinds -update-golden
var updateGolden = flag.Bool("update-golden", false, "rewrite the testdata/*-testcase.{yaml,json} goldens from the fixtures")

const (
	goldenHTTPYAML = "testdata/http-testcase.yaml"
	goldenHTTPJSON = "testdata/http-testcase.json"
	goldenGRPCYAML = "testdata/grpc-testcase.yaml"
	goldenGRPCJSON = "testdata/grpc-testcase.json"
)

func goldenLogger(t *testing.T) *zap.Logger {
	t.Helper()
	return zap.NewNop()
}

