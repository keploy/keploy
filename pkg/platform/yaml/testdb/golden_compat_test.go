// encodeBoth returns the YAML and JSON on-disk bytes for a test case, through
// exactly the code paths the recorder uses.
func encodeBoth(t *testing.T, tc models.TestCase) (yamlBytes, jsonBytes []byte) {
	t.Helper()
	log := goldenLogger(t)

	doc, err := EncodeTestcase(tc, log)
	if err != nil {
		t.Fatalf("EncodeTestcase(%s): %v", tc.Kind, err)
	}
	yamlBytes, err = yaml.MarshalDoc(yaml.FormatYAML, doc)
	if err != nil {
		t.Fatalf("MarshalDoc yaml: %v", err)
	}

	jsonDoc, err := EncodeTestcaseJSON(tc, log)
	if err != nil {
		t.Fatalf("EncodeTestcaseJSON(%s): %v", tc.Kind, err)
	}
	jsonBytes, err = json.MarshalIndent(jsonDoc, "", "  ")
	if err != nil {
		t.Fatalf("marshal json doc: %v", err)
	}
	jsonBytes = append(jsonBytes, '\n')
	return yamlBytes, jsonBytes
}

func compareGolden(t *testing.T, path string, got []byte) {
	t.Helper()
	if *updateGolden {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("mkdir: %v", err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
		t.Logf("regenerated %s (%d bytes)", path, len(got))
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (regenerate with -update-golden ONLY if the change is intended)", path, err)
	}
	if string(got) != string(want) {
		t.Fatalf("%s changed.\nThese bytes are a checked-in on-disk contract: an existing kind must not change\nhow it serializes, and the consumer schema is hand-editable and written by a\nparser in another repository. Regenerate with -update-golden ONLY when the\nschema change is intended and reviewed.\n--- on disk ---\n%s\n--- produced now ---\n%s", path, want, got)
	}
}

// The whole backward-compatibility claim in one test: an HTTP and a gRPC test
// case must serialize to exactly the bytes the pre-consumer build produced, in
// both storage formats.
func TestExistingKindsSerializeByteIdentically(t *testing.T) {
	httpYAML, httpJSON := encodeBoth(t, httpFixture())
	compareGolden(t, goldenHTTPYAML, httpYAML)
	compareGolden(t, goldenHTTPJSON, httpJSON)

	grpcYAML, grpcJSON := encodeBoth(t, grpcFixture())
	compareGolden(t, goldenGRPCYAML, grpcYAML)
	compareGolden(t, goldenGRPCJSON, grpcJSON)
}

// And the decode side: the checked-in bytes must decode into the same
// TestCase, then re-encode to the same bytes. This is what catches a decode
// arm that accidentally consumes a field an existing kind needs.
func TestExistingKindsRoundTripThroughDecode(t *testing.T) {
	log := goldenLogger(t)
	cases := []struct {
		name     string
		yamlPath string
		jsonPath string
	}{
		{"http", goldenHTTPYAML, goldenHTTPJSON},
		{"grpc", goldenGRPCYAML, goldenGRPCJSON},
	}
	for _, c := range cases {
		t.Run(c.name+"/yaml", func(t *testing.T) {
			raw, err := os.ReadFile(c.yamlPath)
			if err != nil {
				t.Fatalf("read: %v", err)
			}
			doc, err := yaml.UnmarshalDoc(yaml.FormatYAML, raw)
			if err != nil {
				t.Fatalf("UnmarshalDoc: %v", err)
			}
			tc, err := Decode(doc, log)
			if err != nil {
				t.Fatalf("Decode: %v", err)
			}
			again, err := EncodeTestcase(*tc, log)
			if err != nil {
				t.Fatalf("re-encode: %v", err)
			}
			out, err := yaml.MarshalDoc(yaml.FormatYAML, again)
			if err != nil {
				t.Fatalf("re-marshal: %v", err)
			}
			if string(out) != string(raw) {
				t.Fatalf("%s did not survive decode->encode.\n--- in ---\n%s\n--- out ---\n%s", c.yamlPath, raw, out)
			}
		})
		t.Run(c.name+"/json", func(t *testing.T) {
			raw, err := os.ReadFile(c.jsonPath)
			if err != nil {
				t.Fatalf("read: %v", err)
			}
			var jsonDoc yaml.NetworkTrafficDocJSON
			if err := json.Unmarshal(raw, &jsonDoc); err != nil {
				t.Fatalf("unmarshal: %v", err)
			}
			tc, err := DecodeJSON(&jsonDoc, log)
			if err != nil {
				t.Fatalf("DecodeJSON: %v", err)
			}
			again, err := EncodeTestcaseJSON(*tc, log)
			if err != nil {
				t.Fatalf("re-encode: %v", err)
			}
			out, err := json.MarshalIndent(again, "", "  ")
			if err != nil {
				t.Fatalf("re-marshal: %v", err)
			}
			out = append(out, '\n')
			if string(out) != string(raw) {
				t.Fatalf("%s did not survive decode->encode.\n--- in ---\n%s\n--- out ---\n%s", c.jsonPath, raw, out)
			}
		})
	}
}
