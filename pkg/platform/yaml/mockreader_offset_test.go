package yaml

import (
	"bytes"
	"context"
	"io"
	"os"
	"path/filepath"
	"testing"

	"go.uber.org/zap"
)

// A replay leaves each mock's payload in its mock file and reads the mock's
// document back, alone, to send it: DocOffset must be where the bytes
// ReadNextDocument returned for the document are in the file, whatever the
// file's line endings, its header, its separators and its last line.
func TestMockReaderDocOffsetIsWhereTheDocumentIsInTheFile(t *testing.T) {
	for _, tc := range []struct {
		name    string
		format  Format
		content string
		docs    int
	}{
		{"yaml with a header comment", FormatYAML,
			"# Generated by Keploy (v3)\nversion: v1\nkind: Http\nname: mock-0\n---\nversion: v1\nkind: Http\nname: mock-1\n", 2},
		{"yaml with leading and doubled separators", FormatYAML,
			"---\n---\nversion: v1\nname: mock-0\n---\n\n---\nversion: v1\nname: mock-1\n---\n", 2},
		{"yaml with CRLF line endings", FormatYAML,
			"# header\r\n---\r\nversion: v1\r\nname: mock-0\r\n---\r\nversion: v1\r\nname: mock-1\r\n", 2},
		{"yaml with no final newline", FormatYAML,
			"version: v1\nname: mock-0\n---\nversion: v1\nname: mock-1", 2},
		{"yaml whose body holds an indented separator", FormatYAML,
			"version: v1\nname: mock-0\nbody: |\n    ---\n    a: b\n---\nname: mock-1\n", 2},
		{"ndjson with blank lines and indentation", FormatJSON,
			"{\"name\":\"mock-0\"}\n\n   {\"name\":\"mock-1\"}  \n\t{\"name\":\"mock-2\"}\n", 3},
		{"ndjson with no final newline", FormatJSON,
			"{\"name\":\"mock-0\"}\r\n  {\"name\":\"mock-1\"}", 2},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := os.WriteFile(filepath.Join(dir, "mocks."+tc.format.FileExtension()), []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}
			r, err := NewMockReaderF(context.Background(), zap.NewNop(), dir, "mocks", tc.format)
			if err != nil {
				t.Fatal(err)
			}
			defer r.Close()
			n := 0
			for {
				doc, err := r.ReadNextDocument()
				if err == io.EOF {
					break
				}
				if err != nil {
					t.Fatal(err)
				}
				if len(bytes.TrimSpace(doc)) == 0 {
					continue
				}
				n++
				off := r.DocOffset()
				if off < 0 || off+int64(len(doc)) > int64(len(tc.content)) {
					t.Fatalf("document %d: offset %d and length %d are outside the file", n, off, len(doc))
				}
				if got := tc.content[off : off+int64(len(doc))]; got != string(doc) {
					t.Fatalf("document %d: the file at offset %d holds %q; the reader returned %q", n, off, got, doc)
				}
			}
			if n != tc.docs {
				t.Fatalf("read %d documents; want %d", n, tc.docs)
			}
		})
	}
}
