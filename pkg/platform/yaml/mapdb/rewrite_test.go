// handEdited is a mappings.yaml a person or an agent edited: a note at its
// head, fields keploy does not know at the top, on a test entry and on a mock
// entry, and a comment inside it.
const handEdited = `# Generated by Keploy (0.0.1)
# Notes: TestB's mock-1 was moved back by hand, see the README.
version: api.keploy.io/v1beta1
kind: TestMocksMapping
test_set_id: s
reviewed_by: agent
tests:
    - id: o::TestA
      dir: o
      ticket: JIRA-123
      mock_entries:
        - name: mock-0
          kind: Http
          note: keep this one
    # TestB keeps its mock while the payments API migrates
    - id: o::TestB
      dir: o
      mock_entries:
        - name: mock-1
          kind: Http
`

// A rewrite of mappings.yaml, by any of keploy's writers, keeps what a hand
// edit added that keploy does not know -- a field at the top, on a test
// entry, on a mock entry -- the comment at the file's head, its version line
// brought up to date, and a comment on a key keploy writes (the one above a
// test entry): nothing is dropped, so keploy says nothing. Under the proven
// switch, as T2's sets are written.
func TestARewriteKeepsWhatAHandEditAdded(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	for name, write := range map[string]func(*MappingDb) error{
		"UpsertBatch": func(db *MappingDb) error {
			return db.UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::TestC": {{Name: "mock-2", Kind: "Http"}}})
		},
		"UpsertWorker": func(db *MappingDb) error {
			return db.UpsertWorker(context.Background(), "s", []models.MockEntry{{Name: "mock-9"}})
		},
		"MarkRecordedWith": func(db *MappingDb) error {
			return db.MarkRecordedWith(context.Background(), "s", models.RecordedWithS12Routing)
		},
		"MoveToWorker": func(db *MappingDb) error {
			_, err := db.MoveToWorker(context.Background(), "s", []models.MockEntry{{Name: "mock-1", Reason: "moved"}})
			return err
		},
		"Insert": func(db *MappingDb) error {
			return db.Insert(context.Background(), &models.Mapping{TestSetID: "s", TestCases: []models.MappedTestCase{{ID: "o::TestC", Mocks: []models.MockEntry{{Name: "mock-2", Kind: "Http"}}}}})
		},
		// A test the caller writes again keeps what a hand edit added to its
		// entry and to its mock entries.
		"Insert of an edited test": func(db *MappingDb) error {
			return db.Insert(context.Background(), &models.Mapping{TestSetID: "s", TestCases: []models.MappedTestCase{{ID: "o::TestA", Mocks: []models.MockEntry{{Name: "mock-0", Kind: "Http"}}}}})
		},
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
			must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(handEdited), 0o644))
			core, logs := observer.New(zapcore.WarnLevel)
			db := NewWithFormat(zap.New(core), dir, "mappings", yaml.FormatYAML)
			must(t, write(db))
			raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
			must(t, err)
			got := string(raw)
			for _, want := range []string{
				utils.GetVersionAsComment() + "# Notes: TestB's mock-1 was moved back by hand, see the README.\n",
				"reviewed_by: agent\n",
				"ticket: JIRA-123\n",
				"note: keep this one\n",
				"# TestB keeps its mock while the payments API migrates\n",
			} {
				if !strings.Contains(got, want) {
					t.Errorf("the rewrite lost %q:\n%s", want, got)
				}
			}
			if !strings.HasPrefix(got, utils.GetVersionAsComment()) {
				t.Errorf("the rewrite does not start with the current version line:\n%s", got)
			}
			if strings.Contains(got, "(0.0.1)") {
				t.Errorf("the rewrite kept the old version line:\n%s", got)
			}
			if len(logs.All()) != 0 {
				t.Errorf("keploy kept everything, yet logged %v", logs.All())
			}
			back, err := db.GetMapping(context.Background(), "s")
			must(t, err)
			if len(back.TestCases) < 2 {
				t.Fatalf("read back %+v", back)
			}
		})
	}
}

func must(t *testing.T, err error) {
	t.Helper()
	if err != nil {
		t.Fatal(err)
	}
}

// The head is the comment lines a mapping file starts with, its version
// line brought up to this keploy: what a rewrite keeps of it.
func TestHeadComment(t *testing.T) {
	head := string(commentHead([]byte(handEdited)))
	if head != utils.GetVersionAsComment()+"# Notes: TestB's mock-1 was moved back by hand, see the README.\n" {
		t.Fatalf("head %q", head)
	}
	if got := commentHead([]byte("version: v\n")); len(got) != 0 {
		t.Fatalf("a file with no head comment has none, got %q", got)
	}
	// A note a blank line sets apart from the version line is the head's.
	if got := string(commentHead([]byte("# Generated by Keploy (0.0.1)\n\n# my note\nversion: v\n"))); got != utils.GetVersionAsComment()+"\n# my note\n" {
		t.Fatalf("head %q", got)
	}
	if got := commentHead([]byte("\n\nversion: v\n")); len(got) != 0 {
		t.Fatalf("blank lines alone are no head, got %q", got)
	}
}

// The head comment is written once, even when the file's first field is
// one keploy does not know (YAML hangs the comment on that field), and a
// note a blank line sets apart is kept without a word.
func TestTheHeadIsWrittenOnce(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	for name, file := range map[string]string{
		"unknown first field":          "# Generated by Keploy (0.0.1)\n# note\nreviewed_by: agent\nversion: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\n",
		"blank line in the head":       "# Generated by Keploy (0.0.1)\n\n# note\nversion: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\n",
		"head after a document marker": "---\n# Generated by Keploy (0.0.1)\n# note\nreviewed_by: agent\nversion: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\n",
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
			must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(file), 0o644))
			core, logs := observer.New(zapcore.WarnLevel)
			db := NewWithFormat(zap.New(core), dir, "mappings", yaml.FormatYAML)
			must(t, db.UpsertWorker(context.Background(), "s", []models.MockEntry{{Name: "mock-9"}}))
			raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
			must(t, err)
			got := string(raw)
			if strings.Count(got, "# note\n") != 1 || strings.Contains(got, "(0.0.1)") || !strings.HasPrefix(got, utils.GetVersionAsComment()) {
				t.Fatalf("the head is not written once, current:\n%s", got)
			}
			if len(logs.All()) != 0 {
				t.Fatalf("keploy said it dropped a comment it kept: %v", logs.All())
			}
		})
	}
}

// A comment the rewrite keeps, beside a field keploy does not know, is not
// counted as dropped: keploy says it dropped only what the file lost.
func TestACommentKeptBesideAFieldIsNotCountedAsDropped(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	dir := t.TempDir()
	must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
	edited := strings.Replace(handEdited, "reviewed_by: agent\n", "reviewed_by: agent # PR-42\n", 1)
	edited = strings.Replace(edited, "    # TestB keeps its mock while the payments API migrates\n", "", 1)
	must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(edited), 0o644))
	core, logs := observer.New(zapcore.WarnLevel)
	db := NewWithFormat(zap.New(core), dir, "mappings", yaml.FormatYAML)
	must(t, db.UpsertWorker(context.Background(), "s", []models.MockEntry{{Name: "mock-9"}}))
	raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
	must(t, err)
	if !strings.Contains(string(raw), "reviewed_by: agent # PR-42\n") {
		t.Fatalf("the rewrite lost the comment beside reviewed_by:\n%s", raw)
	}
	for _, e := range logs.All() {
		if strings.Contains(e.Message, "dropped") {
			t.Fatalf("keploy said it dropped a comment it kept: %s", e.Message)
		}
	}
	if n := droppedComments([]byte(handEdited), raw); n != 1 {
		t.Fatalf("droppedComments of the hand-edited file against this rewrite = %d, want 1 (the comment on TestB)", n)
	}
}

// A section's entries a writer captures anew (Insert's start-up) keep what
// a hand edit added to each, by mock.
func TestInsertKeepsASectionEntrysFields(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	dir := t.TempDir()
	must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
	file := "version: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\nstartup:\n    - name: mock-9\n      note: flaky boot call\n"
	must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(file), 0o644))
	db := NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML)
	must(t, db.Insert(context.Background(), &models.Mapping{TestSetID: "s", Startup: []models.MockEntry{{Name: "mock-9"}}}))
	raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
	must(t, err)
	if !strings.Contains(string(raw), "note: flaky boot call") {
		t.Fatalf("the start-up entry's note was lost:\n%s", raw)
	}
}

// Insert, keploy test's whole-file write, rebuilds the file from each test's
// mocks; under the proven switch it keeps every entry's fields beside the
// mocks (cases, case_mocks, case_steps, dir, starts, at, real) and the boots
// and suites sections, those of a test it writes again too. A field the
// caller sets replaces the file's; one it leaves unset keeps it.
func TestInsertKeepsWhatItDoesNotWrite(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	file := `version: api.keploy.io/v1beta1
kind: TestMocksMapping
test_set_id: s
tests:
    - id: o::TestA
      mock_entries:
        - name: mock-0
      cases: [test-1, test-2]
      case_mocks:
        test-1: [mock-0]
      case_steps:
        test-2: step
      dir: o
      starts: 2
      at: 2026-10-22T09:00:00Z
      real: [mock-3]
    - id: o::TestB
      mock_entries:
        - name: mock-1
      dir: o
      cases: [test-3]
suites:
    - dir: o
      start: 2026-10-22T08:59:00Z
      end: 2026-10-22T09:01:00Z
boots:
    - dir: o
      key: k
      program: p
      mocks: [{name: mock-9}]
`
	dir := writeSet(t, file)
	db := NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML)
	must(t, db.Insert(context.Background(), &models.Mapping{TestSetID: "s", TestCases: []models.MappedTestCase{
		{ID: "o::TestA", Mocks: []models.MockEntry{{Name: "mock-5"}}, Dir: "o2"},
		{ID: "o::TestC", Mocks: []models.MockEntry{{Name: "mock-6"}}, Dir: "p", Cases: []string{"test-4"}},
	}}))
	got, err := db.GetMapping(context.Background(), "s")
	must(t, err)
	byID := map[string]models.MappedTestCase{}
	for _, e := range got.TestCases {
		byID[e.ID] = e
	}
	a, b, c := byID["o::TestA"], byID["o::TestB"], byID["o::TestC"]
	if len(a.Mocks) != 1 || a.Mocks[0].Name != "mock-5" {
		t.Errorf("TestA's mocks = %+v, want the written mock-5", a.Mocks)
	}
	if a.Dir != "o2" {
		t.Errorf("TestA's dir = %q, want the written o2", a.Dir)
	}
	if strings.Join(a.Cases, ",") != "test-1,test-2" || strings.Join(a.CaseMocks["test-1"], ",") != "mock-0" || a.CaseSteps["test-2"] != "step" ||
		a.Starts != 2 || !a.At.Equal(time.Date(2026, 10, 22, 9, 0, 0, 0, time.UTC)) || strings.Join(a.Real, ",") != "mock-3" {
		t.Errorf("TestA lost what the write left unset: %+v", a)
	}
	if b.Dir != "o" || strings.Join(b.Cases, ",") != "test-3" || len(b.Mocks) != 1 || b.Mocks[0].Name != "mock-1" {
		t.Errorf("TestB, which the write does not name, changed: %+v", b)
	}
	if c.Dir != "p" || strings.Join(c.Cases, ",") != "test-4" {
		t.Errorf("TestC lost what the write set: %+v", c)
	}
	if len(got.Suites) != 1 || got.Suites[0].Dir != "o" || len(got.Boots) != 1 || got.Boots[0].Program != "p" || len(got.Boots[0].Mocks) != 1 || got.Boots[0].Mocks[0].Name != "mock-9" {
		t.Errorf("the suites or boots were lost: suites %+v, boots %+v", got.Suites, got.Boots)
	}
}

// UpsertWorker, which replaces the worker scope with the one a record
// captured, keeps what a hand edit added to an entry of the same mock.
func TestUpsertWorkerKeepsAnEntrysFields(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	dir := t.TempDir()
	must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
	file := "version: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\nworker:\n    - name: mock-9\n      note: flaky poll\n"
	must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(file), 0o644))
	db := NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML)
	must(t, db.UpsertWorker(context.Background(), "s", []models.MockEntry{{Name: "mock-9"}, {Name: "mock-10"}}))
	raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
	must(t, err)
	if !strings.Contains(string(raw), "note: flaky poll") || !strings.Contains(string(raw), "mock-10") {
		t.Fatalf("the worker entry's note was lost, or the new entry not written:\n%s", raw)
	}
}

// A test entry with both mock lists is refused with a BothMockListsError
// naming it, through the decode a replay reads the file with, in YAML (a
// mocks: list a merge key brings included) and in JSON: a reader that
// checks a set names the entry from it.
func TestBothMockListsIsATypedRefusalNamingTheTest(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	for name, c := range map[string]struct {
		format yaml.Format
		doc    string
	}{
		"yaml":       {yaml.FormatYAML, "version: v\ntests:\n    - id: pkg::TestA\n      mocks: [{name: mock-0}]\n      mock_entries: [{name: mock-1}]\n"},
		"yaml merge": {yaml.FormatYAML, "x-base: &base\n    mocks: [{name: mock-0}]\ntests:\n    - <<: *base\n      id: pkg::TestA\n      mock_entries: [{name: mock-1}]\n"},
		"json":       {yaml.FormatJSON, `{"version":"v","tests":[{"id":"pkg::TestA","mocks":[{"name":"mock-0"}],"mock_entries":[{"name":"mock-1"}]}]}`},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := DecodeMappingF([]byte(c.doc), zap.NewNop(), c.format)
			var both *models.BothMockListsError
			if !errors.As(err, &both) || both.Test != "pkg::TestA" {
				t.Fatalf("err %v (%T); want a BothMockListsError naming pkg::TestA", err, err)
			}
			if !strings.Contains(err.Error(), "`mocks` and `mock_entries`") {
				t.Fatalf("the refusal's words changed: %v", err)
			}
		})
	}
}
