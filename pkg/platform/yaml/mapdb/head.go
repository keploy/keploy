// versionLine starts the comment line keploy writes at a mapping file's head
// (utils.GetVersionAsComment).
const versionLine = "# Generated by Keploy"

// encodeOver encodes mapping in format to replace old, the file's bytes
// before (nil for a new file). Under the proven switch a YAML file keeps
// old's head comment, the
// comment lines it starts with, its "# Generated by Keploy" line brought up
// to this keploy; a file with none gets this keploy's line when it is new,
// or always. The fields old had that this keploy does not know are kept by
// the mapping itself (models.Mapping, MappedTestCase and MockEntry keep
// them). A comment anywhere else in old cannot be kept by a rewrite of the
// decoded file: keploy says how many lines it dropped, so an edit is never
// lost without a word.
func (db *MappingDb) encodeOver(mapping *models.Mapping, format yaml.Format, old []byte, always bool, testSetID string) ([]byte, error) {
	data, err := EncodeMappingF(mapping, db.logger, format)
	if err != nil || format != yaml.FormatYAML {
		return data, err
	}
	if !provenswitch.On() {
		// Without the proven switch the file is written as it was before
		// keploy kept its head: this keploy's line on a new file, or always.
		if old == nil || always {
			data = append([]byte(utils.GetVersionAsComment()), data...)
		}
		return data, nil
	}
	head := commentHead(old)
	switch {
	case len(head) > 0:
		data = append(head, data...)
	case old == nil || always:
		data = append([]byte(utils.GetVersionAsComment()), data...)
	}
	if n := DroppedComments(old, data); n > 0 {
		db.logger.Warn(fmt.Sprintf("keploy rewrote the set's mappings file and dropped %d comment line(s) that were not at its head", n),
			zap.String("testSetID", testSetID),
			zap.String("next_step", "keploy keeps the comment lines a mappings file starts with, and every field, even one it does not know; move a note to the top of the file"))
	}
	return data, nil
}

// HeadComment is the comment lines the mapping file data starts with, its "#
// Generated by Keploy" line brought up to this keploy (commentHead): what a
// writer that builds the file anew outside this package keeps of it. Empty
// when data starts with none.
func HeadComment(data []byte) []byte {
	return commentHead(data)
}

// commentHead is the comment lines data starts with, and the blank lines
// between them, its "# Generated by Keploy" line replaced by this keploy's;
// nil when data starts with no comment. A document marker (---) or a
// directive (%YAML) before them is skipped: the writer writes neither.
func commentHead(data []byte) []byte {
	var head bytes.Buffer
	blanks := 0
	for _, line := range strings.SplitAfter(string(data), "\n") {
		t := strings.TrimSpace(line)
		if t == "" {
			blanks++
			continue
		}
		if head.Len() == 0 && (t == "---" || strings.HasPrefix(t, "%")) {
			continue
		}
		if !strings.HasPrefix(t, "#") {
			break
		}
		if head.Len() > 0 {
			head.WriteString(strings.Repeat("\n", blanks))
		}
		blanks = 0
		if strings.HasPrefix(t, versionLine) {
			head.WriteString(utils.GetVersionAsComment())
			continue
		}
		head.WriteString(strings.TrimRight(line, "\r\n") + "\n")
	}
	if head.Len() == 0 {
		return nil
	}
	return head.Bytes()
}

// DroppedComments is how many of the comment lines old, a mapping file's
// bytes before a rewrite, holds that written, its bytes after, does not:
// each line counted as often as it appears, a "# Generated by Keploy" line
// not at all (a rewrite brings it up to date). A comment the rewrite kept,
// at the head or beside a field keploy does not know, is not dropped. 0 for
// old that does not parse.
func DroppedComments(old, written []byte) int {
	if !bytes.Contains(pastHead(old), []byte("#")) {
		// Every comment is in the head, which a rewrite keeps: no file is
		// parsed (a recording's batches rewrite the file often).
		return 0
	}
	kept := map[string]int{}
	for _, l := range commentTexts(written) {
		kept[l]++
	}
	n := 0
	for _, l := range commentTexts(old) {
		if kept[l] > 0 {
			kept[l]--
			continue
		}
		n++
	}
	return n
}

// pastHead is data after the comment and blank lines it starts with, and a
// document marker or directive before them (commentHead).
func pastHead(data []byte) []byte {
	comments := false
	for len(data) > 0 {
		line := data
		if i := bytes.IndexByte(data, '\n'); i >= 0 {
			line = data[:i+1]
		}
		t := bytes.TrimSpace(line)
		switch {
		case len(t) == 0:
		case t[0] == '#':
			comments = true
		case !comments && (string(t) == "---" || t[0] == '%'):
		default:
			return data
		}
		data = data[len(line):]
	}
	return nil
}

// commentTexts is the comment lines the YAML document data holds, wherever
// they are, each trimmed, without the "# Generated by Keploy" line; nil for
// data that does not parse.
func commentTexts(data []byte) []string {
	if len(data) == 0 {
		return nil
	}
	var doc yamlLib.Node
	if yamlLib.Unmarshal(data, &doc) != nil {
		return nil
	}
	var out []string
	var walk func(*yamlLib.Node)
	walk = func(x *yamlLib.Node) {
		for _, c := range []string{x.HeadComment, x.LineComment, x.FootComment} {
			for _, l := range strings.Split(c, "\n") {
				if l = strings.TrimSpace(l); strings.HasPrefix(l, "#") && !strings.HasPrefix(l, versionLine) {
					out = append(out, l)
				}
			}
		}
		for _, child := range x.Content {
			walk(child)
		}
	}
	walk(&doc)
	return out
}
