// writeSet writes the mappings file body for set s under a new keploy folder
// and returns the folder.
func writeSet(t *testing.T, body string) string {
	t.Helper()
	dir := t.TempDir()
	must(t, os.MkdirAll(filepath.Join(dir, "s"), 0o755))
	if body != "" {
		must(t, os.WriteFile(filepath.Join(dir, "s", "mappings.yaml"), []byte(body), 0o644))
	}
	return dir
}

func readSet(t *testing.T, dir string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(dir, "s", "mappings.yaml"))
	must(t, err)
	return string(raw)
}

// Without the proven switch keploy writes the mappings file as it did
// before it kept hand edits: a field it does not know and the comments are
// dropped, and each writer puts its "# Generated by Keploy" line where it
// always did (Insert on every write, UpsertBatch on a file it creates,
// UpsertBoots never).
func TestWithTheSwitchOffTheFileIsWrittenAsBefore(t *testing.T) {
	t.Setenv(provenswitch.Env, "")
	dir := writeSet(t, handEdited)
	must(t, NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML).UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::TestC": {{Name: "mock-2", Kind: "Http"}}}))
	got := readSet(t, dir)
	for _, gone := range []string{"reviewed_by", "ticket", "note:", "# Notes", "# TestB", "# Generated by Keploy"} {
		if strings.Contains(got, gone) {
			t.Errorf("with the switch off the rewrite kept %q:\n%s", gone, got)
		}
	}
	for name, c := range map[string]struct {
		write func(*MappingDb) error
		head  bool
	}{
		"Insert": {func(db *MappingDb) error {
			return db.Insert(context.Background(), &models.Mapping{TestSetID: "s", TestCases: []models.MappedTestCase{{ID: "o::T", Mocks: []models.MockEntry{{Name: "mock-0"}}}}})
		}, true},
		"UpsertBatch": {func(db *MappingDb) error {
			return db.UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::T": {{Name: "mock-0"}}})
		}, true},
		"UpsertBoots": {func(db *MappingDb) error {
			return db.UpsertBoots(context.Background(), "s", []models.BootSpec{{Dir: "o", Key: "k", Program: "p"}})
		}, false},
	} {
		t.Run(name, func(t *testing.T) {
			dir := writeSet(t, "")
			must(t, c.write(NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML)))
			if got := strings.HasPrefix(readSet(t, dir), "# Generated by Keploy"); got != c.head {
				t.Fatalf("a new file starts with keploy's line: %v, want %v", got, c.head)
			}
		})
	}
}

// Every writer keeps a hand edit, those that replace a section whole too:
// UpsertConcurrency's shared: and UpsertBoots' boots, matched by mock name
// and by boot.
func TestWritersThatReplaceASectionKeepItsEntriesFields(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	file := "version: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\nboots:\n    - dir: o\n      key: k\n      program: p\n      place: \"\"\n      n: 0\n      ready: false\n      mocks: []\n      owner: platform-team\nshared:\n    - name: mock-7\n      note: shared by A and B\n"
	dir := writeSet(t, file)
	db := NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML)
	must(t, db.UpsertConcurrency(context.Background(), "s", []models.ConcurrencyGroup{{ID: "g", Tests: []string{"o::TestA"}}}, []models.MockEntry{{Name: "mock-7"}}))
	must(t, db.UpsertBoots(context.Background(), "s", []models.BootSpec{{Dir: "o", Key: "k", Program: "p2"}}))
	got := readSet(t, dir)
	for _, want := range []string{"note: shared by A and B\n", "owner: platform-team\n", "program: p2\n"} {
		if !strings.Contains(got, want) {
			t.Errorf("the rewrite lost %q:\n%s", want, got)
		}
	}
}

// A kept field stays where it was among the fields around it: a note at the
// top of the file stays above a long tests: list.
func TestAKeptFieldStaysInItsPlace(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	file := "note: read me first\nversion: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\n"
	dir := writeSet(t, file)
	must(t, NewWithFormat(zap.NewNop(), dir, "mappings", yaml.FormatYAML).UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::TestB": {{Name: "mock-1"}}}))
	got := readSet(t, dir)
	if n, tests := strings.Index(got, "note: read me first"), strings.Index(got, "tests:"); n < 0 || n > tests {
		t.Fatalf("the note is not above tests: any more:\n%s", got)
	}
}

// A large field written out without aliases is kept whatever its size: the
// alias bound counts only what aliases bring in. A field whose aliases
// expand past it (an alias bomb) is not kept, and keploy says which; an
// aliased field is written without the anchors, never twice.
func TestTheAliasBoundCountsOnlyWhatAliasesBringIn(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	head := "version: api.keploy.io/v1beta1\nkind: TestMocksMapping\ntest_set_id: s\ntests:\n    - id: o::TestA\n      mock_entries:\n        - name: mock-0\n"
	var routes strings.Builder
	routes.WriteString("x-routes:\n")
	for i := 0; i < 2600; i++ {
		fmt.Fprintf(&routes, "    - {path: /r%d, method: GET, owner: team, ok: true}\n", i)
	}
	dir := writeSet(t, head+routes.String())
	core, logs := observer.New(zapcore.WarnLevel)
	db := NewWithFormat(zap.New(core), dir, "mappings", yaml.FormatYAML)
	must(t, db.UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::TestB": {{Name: "mock-1"}}}))
	if got := readSet(t, dir); !strings.Contains(got, "path: /r2599") || len(logs.All()) != 0 {
		t.Fatalf("a 2,600-item field written out was not kept, or keploy warned %v", logs.All())
	}

	// Each level doubles the nodes the one below brings: 2^20 at the top.
	var bomb strings.Builder
	bomb.WriteString("x-l0: &l0 [a, b]\n")
	for i := 1; i <= 20; i++ {
		fmt.Fprintf(&bomb, "x-l%d: &l%d [*l%d, *l%d]\n", i, i, i-1, i-1)
	}
	dir = writeSet(t, head+bomb.String())
	core, logs = observer.New(zapcore.WarnLevel)
	db = NewWithFormat(zap.New(core), dir, "mappings", yaml.FormatYAML)
	must(t, db.UpsertBatch(context.Background(), "s", map[string][]models.MockEntry{"o::TestB": {{Name: "mock-1"}}}))
	got := readSet(t, dir)
	if strings.Contains(got, "x-l20") {
		t.Fatalf("the alias bomb was kept")
	}
	if !strings.Contains(got, "x-l1:") {
		t.Fatalf("a small aliased field was not kept:\n%.400s", got)
	}
	said := false
	for _, e := range logs.All() {
		if strings.Contains(e.Message, "could not keep") {
			for _, f := range e.ContextMap()["fields"].([]interface{}) {
				if f == "x-l20" {
					said = true
				}
			}
		}
	}
	if !said {
		t.Fatalf("keploy did not name the field it could not keep: %v", logs.All())
	}
	if strings.Contains(got, "&l") || strings.Contains(got, "*l") {
		t.Fatalf("a kept field is written with anchors or aliases:\n%.400s", got)
	}
}

// EncodeOver, which a writer outside mapdb writes the file with, keeps what
// a hand edit added and says what it could not keep.
func TestEncodeOver(t *testing.T) {
	m, err := DecodeMapping([]byte(handEdited), zap.NewNop())
	must(t, err)
	m.TestCases = append(m.TestCases, models.MappedTestCase{ID: "o::TestC", Mocks: []models.MockEntry{{Name: "mock-2"}}})
	data, unkept, err := EncodeOver(m, []byte(handEdited))
	must(t, err)
	got := string(data)
	for _, want := range []string{utils.GetVersionAsComment() + "# Notes: TestB's mock-1 was moved back by hand, see the README.\n", "reviewed_by: agent\n", "ticket: JIRA-123\n", "note: keep this one\n", "o::TestC"} {
		if !strings.Contains(got, want) {
			t.Errorf("EncodeOver lost %q:\n%s", want, got)
		}
	}
	if unkept.Comments != 0 || len(unkept.Fields) != 0 {
		t.Fatalf("EncodeOver kept everything, yet reports %+v", unkept)
	}
	data, _, err = EncodeOver(m, nil)
	must(t, err)
	if !strings.HasPrefix(string(data), utils.GetVersionAsComment()) {
		t.Fatalf("a new file does not start with keploy's line:\n%.200s", data)
	}
}
