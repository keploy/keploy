// Under the proven switch, the note a test's harness sent with its end is
// written beside its mocks and read back. A later record that ran the test
// replaces it, none included: it is of the run whose calls the entry now
// holds. A write for a test that did not run in it (no begin), and a write
// of the test's mocks alone, keep it.
func TestUpsertCasesKeepsEachTestsNote(t *testing.T) {
	t.Setenv(provenswitch.Env, "1")
	t0 := time.Date(2026, 11, 2, 9, 0, 0, 0, time.UTC)
	const n1, n2 = "frames /a:2\n", "draws 7"
	for _, format := range []yaml.Format{yaml.FormatYAML, yaml.FormatJSON} {
		t.Run(string(format), func(t *testing.T) {
			db := NewWithFormat(zap.NewNop(), t.TempDir(), "", format)
			ctx := context.Background()
			require.NoError(t, db.UpsertBatch(ctx, "set", map[string][]models.MockEntry{"t1": {{Name: "mock-0"}}}))
			require.NoError(t, db.UpsertCases(ctx, "set", map[string]models.MappedTestCase{
				"t1": {At: t0, Note: n1}, "t2": {At: t0, Note: n1}, "t3": {At: t0, Note: n1},
			}, nil, nil))
			require.NoError(t, db.UpsertCases(ctx, "set", map[string]models.MappedTestCase{
				"t1": {Dir: "pkg"}, "t2": {At: t0.Add(time.Hour), Note: n2}, "t3": {At: t0.Add(time.Hour)},
			}, nil, nil))
			require.NoError(t, db.UpsertBatch(ctx, "set", map[string][]models.MockEntry{"t1": {{Name: "mock-1"}}}))
			mapping, err := db.GetMapping(ctx, "set")
			require.NoError(t, err)
			byID := map[string]models.MappedTestCase{}
			for _, tc := range mapping.TestCases {
				byID[tc.ID] = tc
			}
			require.Equal(t, n1, byID["t1"].Note, "a write without the test's run keeps its note")
			require.Equal(t, "mock-1", byID["t1"].Mocks[len(byID["t1"].Mocks)-1].Name)
			require.Equal(t, n2, byID["t2"].Note, "a re-record's note replaces it")
			require.Empty(t, byID["t3"].Note, "a later record whose harness sent none replaces it")
		})
	}
}

// A write of the tests' mocks that rebuilds their entries keeps each entry's
// note, the one written over the one on disk (entryOver).
func TestEntryOverKeepsTheNote(t *testing.T) {
	o := models.MappedTestCase{ID: "t1", Note: "draws 7"}
	require.Equal(t, "draws 7", entryOver(o, models.MappedTestCase{ID: "t1", Dir: "pkg"}).Note)
	require.Equal(t, "draws 8", entryOver(o, models.MappedTestCase{ID: "t1", Note: "draws 8"}).Note)
}

// handNoted is a set whose TestA a hand edit gave a note: of its own, beside
// the note its harness sent (harness_note:).
const handNoted = `# Generated by Keploy (0.0.1)
version: api.keploy.io/v1beta1
kind: TestMocksMapping
test_set_id: s
tests:
    - id: o::TestA
      note: checked by hand
      harness_note: draws 7
      mock_entries:
        - name: mock-0
          kind: Http
`

// A note: a hand edit wrote on a test entry is the hand edit's: it is not
// the harness's note, and a write over the file keeps it as written beside
// the harness's new one.
func TestAHandWrittenNoteOnATestIsKeptBesideTheHarnessNote(t *testing.T) {
	m, err := DecodeMapping([]byte(handNoted), zap.NewNop())
	require.NoError(t, err)
	require.Len(t, m.TestCases, 1)
	require.Equal(t, "draws 7", m.TestCases[0].Note)
	m.TestCases[0].Note = "draws 8"
	data, unkept, err := EncodeOver(m, []byte(handNoted), nil)
	require.NoError(t, err)
	got := string(data)
	require.Contains(t, got, "note: checked by hand\n")
	require.Contains(t, got, "harness_note: draws 8\n")
	require.NotContains(t, got, "draws 7")
	require.Zero(t, unkept.Comments)
	require.Empty(t, unkept.Fields)
	require.Empty(t, unkept.Dropped)
}
