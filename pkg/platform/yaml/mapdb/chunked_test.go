// A mappings file read a few test entries at a time is the file read whole:
// keploy's own files, the golden files of this package, every writer's
// fixture, files whose head a person wrote, values YAML writes as a block of
// text, quoted, long or not ASCII, and files laid out otherwise, which are
// read whole. keploy's own files are read a few entries at a time, and found
// to hold no hand edit; a file a person edited is not.
func TestAMappingsFileReadAFewEntriesAtATimeIsTheFileReadWhole(t *testing.T) {
	eachSwitch(t, readAFewEntriesAtATime)
}

func readAFewEntriesAtATime(t *testing.T) {
	type fixture struct {
		data []byte
		// known: whether it is read a few entries at a time (chunked) and
		// holds no hand edit (plain) is known, and checked.
		known, chunked, plain bool
	}
	fixtures := map[string]fixture{}
	gen := generatedMapping()
	enc, err := marshalMappingYAML(gen)
	if err != nil {
		t.Fatal(err)
	}
	fixtures["generated"] = fixture{enc, true, true, true}
	fixtures["generated, keploy's line on top"] = fixture{append([]byte("# Generated by Keploy (0.0.1)\n"), enc...), true, true, true}
	fixtures["generated, CRLF"] = fixture{[]byte(strings.ReplaceAll(string(enc), "\n", "\r\n")), true, true, false}
	fixtures["generated, a comment on an entry"] = fixture{[]byte(strings.Replace(string(enc), "    - id: test-70\n", "    - id: test-70 # flaky\n", 1)), true, true, false}
	fixtures["generated, a comment line among the entries"] = fixture{[]byte(strings.Replace(string(enc), "    - id: test-70\n", "    # flaky below\n    - id: test-70\n", 1)), true, false, false}
	fixtures["generated, a field a person added"] = fixture{[]byte(strings.Replace(string(enc), "    - id: test-70\n", "    - id: test-70\n      owner: payments\n", 1)), true, true, false}
	fixtures["generated, an anchor another chunk names"] = fixture{[]byte(strings.Replace(strings.Replace(string(enc),
		"    - id: test-1\n", "    - id: &first test-1\n", 1), "    - id: test-190\n", "    - id: *first\n", 1)), true, false, false}
	// YAML reads a stream's first document: so does the read of a few
	// entries at a time.
	// yaml.v3 writes a block of text whose first line alone is indented
	// with an indent it cannot read back: read whole or a few entries at a
	// time, the file is refused alike.
	bad := generatedMapping()
	bad.TestCases[70].Key = "  leading spaces\nthen none"
	if enc, err := marshalMappingYAML(bad); err == nil {
		fixtures["generated, a value YAML cannot read back"] = fixture{data: enc}
	}
	// And one it reads back without the indent its every line starts with:
	// read either way it is the same, and its encoding is not the file's.
	lossy := generatedMapping()
	lossy.TestCases[70].Key = "  two\n  indented lines\n"
	if enc, err := marshalMappingYAML(lossy); err == nil {
		fixtures["generated, a value YAML reads back without its indent"] = fixture{enc, true, true, false}
	}
	fixtures["generated, a second document"] = fixture{append(append([]byte{}, enc...), "---\nversion: x\n"...), true, true, false}
	for _, f := range []string{"mappings.yaml", "moved.yaml"} {
		data, err := os.ReadFile(filepath.Join("testdata", "switchoff_golden", f))
		if err != nil {
			t.Fatal(err)
		}
		fixtures["golden "+f] = fixture{data, true, true, true}
	}
	for name, body := range writerFixtures {
		fixtures["writer fixture "+name] = fixture{data: []byte(body)}
	}
	body := strings.TrimPrefix(writerFixtures["full"], "# Generated by Keploy (0.0.1)\n")
	for name, h := range headShapes {
		fixtures["head shape "+name] = fixture{data: []byte(h.old + body)}
	}
	for name, f := range fixtures {
		var whole models.Mapping
		wholeErr := yamlLib.Unmarshal(f.data, &whole)
		got, err := DecodeMappingF(f.data, zap.NewNop(), yaml.FormatYAML)
		if (err != nil) != (wholeErr != nil) {
			t.Errorf("%s: read a few entries at a time it errs %v, read whole %v", name, err, wholeErr)
			continue
		}
		if err == nil && !reflect.DeepEqual(*got, whole) {
			t.Errorf("%s: read a few entries at a time it is not the file read whole:\n got %+v\nwant %+v", name, *got, whole)
		}
		if !f.known {
			continue
		}
		var m models.Mapping
		if chunked := decodeMappingYAML(f.data, &m); chunked != f.chunked {
			t.Errorf("%s: read a few entries at a time: %v, want %v", name, chunked, f.chunked)
			continue
		}
		if f.chunked {
			if plain := plainYAML(f.data, &m); plain != f.plain {
				t.Errorf("%s: found to hold no hand edit: %v, want %v", name, plain, f.plain)
			}
		}
	}
}

// generatedMapping is a mapping of several chunks of tests, with values YAML
// writes as a block of text, quoted, long or not ASCII, and the sections
// beside the tests.
func generatedMapping() *models.Mapping {
	values := []string{
		"plain", "", "line one\nline two\n", "a\n\nb with an empty line\n\n",
		strings.Repeat("long value ", 40), "quote's \"double\" and: colon", "- dash", "# hash", "ünïcödé ✓",
		"trailing space \n", "null", "123", "true", "*alias", "&anchor", "    - indented dash", "tests:",
	}
	m := &models.Mapping{Version: string(models.V1Beta1), Kind: models.MappingKind, TestSetID: "set-0",
		Startup: []models.MockEntry{{Name: "mock-boot", Kind: "Generic"}},
		Worker:  []models.MockEntry{{Name: "mock-w", Kind: "SQS", Reason: "a\n\nb"}}}
	for i := 0; i < 3*mappingChunk+7; i++ {
		v := values[i%len(values)]
		var mocks []models.MockEntry
		for j := 0; j < 1+i%5; j++ {
			mocks = append(mocks, models.MockEntry{Name: fmt.Sprintf("mock-%d-%d", i, j), Kind: "Generic", ReqTimestampMock: "2026-11-19T10:00:00Z", Reason: v})
		}
		m.TestCases = append(m.TestCases, models.MappedTestCase{
			ID:    fmt.Sprintf("test-%d", i),
			Mocks: mocks,
			Real:  []string{v},
			Given: []models.GivenValue{{Name: "g", Value: v}},
			Key:   v,
			Cases: []string{fmt.Sprintf("case-%d", i)},
		})
	}
	// One test of more mocks than a chunk holds.
	for j := 0; j < chunkMocks+10; j++ {
		m.TestCases[5].Mocks = append(m.TestCases[5].Mocks, models.MockEntry{Name: fmt.Sprintf("mock-big-%d", j), Kind: "Redis"})
	}
	return m
}

// An auto-replay round of k8s-proxy builds a MappingDb of its own on the live
// recording directory: it reads the set's mappings file as it starts (the
// set's startup and worker scope and its tests' mocks: three reads) and, with
// UpdateTestMapping on, writes it as it ends (Replayer.StoreMappings ->
// MappingDb.Insert). The recorder's next flush then finds a file another db
// replaced. Each read held 16 times the file, the round's write 32 and the
// next flush 27: on a long recording's file of tens of MB, each a GB or more.
// Each holds little more than the file now.
func TestTheRoundsReadsAndWriteOfTheLiveMappingsFileAndTheNextFlushHoldLittleMoreThanTheFile(t *testing.T) {
	dir := t.TempDir()
	recorder := New(zap.NewNop(), dir, "mappings")
	ctx := context.Background()
	for from := 0; from < 2000; from += 500 {
		if err := recorder.UpsertBatch(ctx, "set-0", liveBatch(from, 500, 20)); err != nil {
			t.Fatalf("build the file: %v", err)
		}
	}
	info, err := os.Stat(filepath.Join(dir, "set-0", "mappings.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	size := uint64(info.Size())
	round := New(zap.NewNop(), dir, "mappings")
	held := map[string]uint64{}
	var readErr error
	held["the round's read of its startup mocks"] = peakHeapOf(func() { _, readErr = round.GetStartup(ctx, "set-0") })
	held["the round's read of its worker scope"] = peakHeapOf(func() { _, readErr = round.GetMapping(ctx, "set-0") })
	var got map[string][]models.MockEntry
	held["the round's read of its tests' mocks"] = peakHeapOf(func() { got, _, readErr = round.Get(ctx, "set-0") })
	if readErr != nil || len(got) != 2000 || len(got["test-1999"]) != 20 {
		t.Fatalf("the round read %d tests (test-1999: %d mocks), err %v; want 2000 of 20", len(got), len(got["test-1999"]), readErr)
	}
	one := liveBatch(5000, 1, 20)
	var writeErr error
	held["the round's write"] = peakHeapOf(func() {
		writeErr = round.Insert(ctx, &models.Mapping{Version: string(models.V1Beta1), Kind: models.MappingKind, TestSetID: "set-0",
			TestCases: []models.MappedTestCase{{ID: "test-5000", Mocks: one["test-5000"]}}})
	})
	if writeErr != nil {
		t.Fatalf("the round's write: %v", writeErr)
	}
	held["the recorder's next flush"] = peakHeapOf(func() { writeErr = recorder.UpsertBatch(ctx, "set-0", liveBatch(2000, 32, 20)) })
	if writeErr != nil {
		t.Fatalf("flush: %v", writeErr)
	}
	// Bound guards live heap against whole-file YAML decode (~11.5-13x live),
	// whole-file encode (~28-35x live), and large transient/retained buffers
	// (a short-lived yaml.Node tree alone in Insert adds ~4x and is outside
	// this 10x bound).
	for what, peak := range held {
		t.Logf("mappings file %d bytes: %s held %d bytes of heap (%.1fx)", size, what, peak, float64(peak)/float64(size))
		if peak > size*10 {
			t.Errorf("%s held %.1fx the %d-byte mappings file: it parsed the file whole", what, float64(peak)/float64(size), size)
		}
	}
	got, _, err = recorder.Get(ctx, "set-0")
	if err != nil || len(got) != 2033 || len(got["test-5000"]) != 20 || len(got["test-2031"]) != 20 {
		t.Fatalf("after the round's write and the next flush the file maps %d tests (test-5000: %d, test-2031: %d), err %v; want 2033",
			len(got), len(got["test-5000"]), len(got["test-2031"]), err)
	}
}

// A test of many mock entries is read a few mock entries at a time, and the
// read is the test read whole: in keploy's own files (first, among others,
// alone, last with no field after its mock entries), and in files laid out
// otherwise or with what does not read alone, which are read whole: CRLF
// lines, a comment among the mock entries, a field a person added to one, an
// alias to an anchor in another part of the list, a line at the entry's
// key column that is no key, a comment at that column among the entries.
func TestATestOfManyMocksReadAFewAtATimeIsTheTestReadWhole(t *testing.T) {
	eachSwitch(t, func(t *testing.T) {
		// Values YAML reads back (entryValues less the block of text whose
		// first line alone is indented, which it does not).
		var readable []string
		for _, v := range entryValues {
			if !strings.HasPrefix(v, "  leading spaces") {
				readable = append(readable, v)
			}
		}
		big := manyMocks("", 3*chunkMocks+17, readable)
		m := &models.Mapping{Version: string(models.V1Beta1), Kind: models.MappingKind, TestSetID: "set-0"}
		m.TestCases = append(m.TestCases, big)
		for i := 0; i < mappingChunk+5; i++ {
			m.TestCases = append(m.TestCases, manyMocks(fmt.Sprintf("test-%d", i), 1+i%3, readable))
		}
		bare := manyMocks("last", chunkMocks+40, readable)
		bare.Cases, bare.CaseMocks, bare.CaseSteps, bare.Dir, bare.Starts = nil, nil, nil, "", 0
		bare.At, bare.End, bare.Real, bare.Given, bare.Key, bare.Seed = time.Time{}, time.Time{}, nil, nil, "", ""
		m.TestCases = append(m.TestCases, bare)
		enc, err := marshalMappingYAML(m)
		if err != nil {
			t.Fatal(err)
		}
		files := map[string][]byte{
			"keploy's":                    enc,
			"CRLF":                        []byte(strings.ReplaceAll(string(enc), "\n", "\r\n")),
			"a comment among the entries": []byte(strings.Replace(string(enc), "        - name: mock-300\n", "        # a note\n        - name: mock-300\n", 1)),
			"a field a person added":      []byte(strings.Replace(string(enc), "        - name: mock-300\n", "        - name: mock-300\n          owner: payments\n", 1)),
			"an alias to another part":    []byte(strings.Replace(strings.Replace(string(enc), "        - name: mock-1\n", "        - name: &one mock-1\n", 1), "        - name: mock-700\n", "        - name: *one\n", 1)),
			"a line at the key column that is no key":       []byte(strings.Replace(string(enc), "        - name: mock-300\n", "      - name: mock-300\n", 1)),
			"a comment at the key column among the entries": []byte(strings.Replace(string(enc), "        - name: mock-300\n", "      # a note\n        - name: mock-300\n", 1)),
		}
		unreadable := manyMocks("unreadable", chunkMocks+40, entryValues)
		if enc, err := marshalMappingYAML(&models.Mapping{Version: string(models.V1Beta1), Kind: models.MappingKind, TestSetID: "set-0",
			TestCases: []models.MappedTestCase{unreadable}}); err == nil {
			files["a value YAML cannot read back"] = enc
		}
		for name, data := range files {
			var whole, chunked models.Mapping
			wholeErr := yamlLib.Unmarshal(data, &whole)
			if !decodeMappingYAML(data, &chunked) {
				// Read whole by the caller, as it is read whole here.
				continue
			}
			if wholeErr != nil {
				t.Fatalf("%s: read a few at a time, though the whole file is refused: %v", name, wholeErr)
			}
			if !reflect.DeepEqual(whole, chunked) {
				for i := range whole.TestCases {
					if i < len(chunked.TestCases) && !reflect.DeepEqual(whole.TestCases[i], chunked.TestCases[i]) {
						t.Fatalf("%s: test %d (%q) read a few mocks at a time differs from the test read whole: %d mocks against %d", name, i, whole.TestCases[i].ID, len(chunked.TestCases[i].Mocks), len(whole.TestCases[i].Mocks))
					}
				}
				t.Fatalf("%s: the file read a few mocks at a time differs from the file read whole (%d tests against %d)", name, len(chunked.TestCases), len(whole.TestCases))
			}
		}
		// keploy's own file is read a few mock entries at a time.
		l, ok := findTests(enc)
		if !ok {
			t.Fatal("keploy's file is not in keploy's layout")
		}
		if _, ok := decodeLargeEntry(enc, l.entries[0], new([]byte)); !ok {
			t.Fatal("the test of many mock entries in keploy's file was not read a few mock entries at a time")
		}
	})
}
