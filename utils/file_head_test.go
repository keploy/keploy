package utils

import (
	"strings"
	"testing"
)

// A recorded file's header says what the file is, never whether it is
// committed: keploy keeps the same file out of git in a pulled Keploy Cloud
// set or beside keploy.lock, and its folder's .gitignore says so. The
// recording's header says it holds what was sent, credentials included.
func TestFileHeadsSayWhatTheFileIsNotWhetherItIsCommitted(t *testing.T) {
	for name, about := range map[string]string{"MocksAbout": MocksAbout, "MappingsAbout": MappingsAbout, "TestCaseAbout": TestCaseAbout} {
		if strings.Contains(strings.ToLower(about), "commit") {
			t.Errorf("%s says whether the file is committed: %q", name, about)
		}
		for _, l := range strings.SplitAfter(about, "\n") {
			if l != "" && !strings.HasPrefix(l, "# ") {
				t.Errorf("%s has a line that is not a comment: %q", name, l)
			}
		}
	}
	if !strings.Contains(MocksAbout, "credentials and tokens included") {
		t.Errorf("MocksAbout does not say the recording holds credentials: %q", MocksAbout)
	}
	t.Setenv("KEPLOY_PROVEN", "1")
	if got := FileHead(MocksAbout); !strings.HasSuffix(got, MocksAbout) || !strings.HasPrefix(got, "# Generated by Keploy") {
		t.Errorf("FileHead under the switch is %q, want the version line then MocksAbout", got)
	}
	t.Setenv("KEPLOY_PROVEN", "")
	if got := FileHead(MocksAbout); strings.Contains(got, MocksAbout) {
		t.Errorf("FileHead with the switch off carries MocksAbout: %q", got)
	}
}
