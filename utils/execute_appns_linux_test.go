// fedoraHosts is a Fedora host's /etc/nsswitch.conf, and fedoraView what the
// application is to see of it: its hosts line without resolve, which has
// glibc ask systemd-resolved, out of keploy's sight (utils/appns).
const (
	fedoraHosts = "# Generated by authselect\npasswd:     files systemd\nhosts:      files myhostname resolve [!UNAVAIL=return] dns\nnetworks:   files\n"
	fedoraView  = "# Generated by authselect\npasswd:     files systemd\nhosts:      files myhostname dns\nnetworks:   files\n"
)

// The application keploy runs natively sees an /etc/nsswitch.conf of its own,
// whose hosts line keploy can see, while the host's file stays byte for byte
// as it was: while keploy and the application run, once keploy is killed with
// SIGKILL (the application runs on, still with its view), and once the
// application is too. And once the application is killed first and keploy
// then returns. Nothing of the view outlives the application.
//
// As root, on a host of the test's own (nsswitchtest), with keploy's part
// played by this test's process in role "keploy": ExecuteCommand, as App.Run
// calls it.
func TestANativeAppSeesItsOwnNsswitchConfAndTheHostsStaysAsItWas(t *testing.T) {
	for _, killFirst := range []string{"keploy", "app"} {
		t.Run("kill_"+killFirst+"_first", func(t *testing.T) {
			if nsswitchtest.Role() == "keploy" {
				runAppAsKeploy(t)
				return
			}
			nsswitchtest.Host(t, []byte(fedoraHosts), func(t *testing.T) { judgeTheHost(t, killFirst) })
		})
	}
}

// runAppAsKeploy is keploy's part: it starts the application as App.Run does
// and says how ExecuteCommand returned, in DIR/returned.
func runAppAsKeploy(t *testing.T) {
	dir := os.Getenv("DIR")
	// The application: it says what it sees (the view, and another file of
	// /etc, the directory the view was made in) and its pid, then waits until
	// the host lets it go (the fifo's only writer closes it, or exits).
	app := fmt.Sprintf("cat %[1]s > %[2]s/seen.tmp && mv %[2]s/seen.tmp %[2]s/seen && cat /etc/passwd > %[2]s/passwd && echo $$ > %[2]s/pid.tmp && mv %[2]s/pid.tmp %[2]s/pid && read x < %[2]s/fifo",
		nsswitchtest.Path, dir)
	cancel := func(cmd *exec.Cmd) func() error { return func() error { return cmd.Process.Kill() } }
	got := ExecuteCommand(context.Background(), zap.NewNop(), app, Native, cancel, time.Second, nil, nil)
	if err := os.WriteFile(filepath.Join(dir, "returned"), []byte(fmt.Sprintf("%v %v", got.Type, got.Err)), 0o600); err != nil {
		t.Fatal(err)
	}
}

func judgeTheHost(t *testing.T, killFirst string) {
	dir := t.TempDir()
	fifo := filepath.Join(dir, "fifo")
	if err := unix.Mkfifo(fifo, 0o600); err != nil {
		t.Fatal(err)
	}
	// Read and write: an open that does not wait for the application, and
	// the fifo's only writer, closed when this host exits however it does.
	hold, err := os.OpenFile(fifo, os.O_RDWR, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer hold.Close()

	hostIsAsItWas := func(when string) {
		t.Helper()
		if got := nsswitchtest.Read(nsswitchtest.Path); got != fedoraHosts {
			t.Errorf("%s, the host's %s is\n%q\nwant it as it was:\n%q", when, nsswitchtest.Path, got, fedoraHosts)
		}
		if mi := nsswitchtest.Read("/proc/self/mountinfo"); strings.Contains(mi, "keploy-nsswitch") {
			t.Errorf("%s, the host has a mount of the view:\n%s", when, mi)
		}
	}

	keploy := nsswitchtest.Spawn(t, "keploy", "DIR="+dir)
	nsswitchtest.Await(t, "the application to say what it sees", func() bool {
		select {
		case <-keploy.Done:
			t.Fatalf("keploy exited before the application started (%v):\n%s", keploy.Err, keploy.Output())
		default:
		}
		_, err := os.Stat(filepath.Join(dir, "pid"))
		return err == nil
	})
	pidText := strings.TrimSpace(nsswitchtest.Read(filepath.Join(dir, "pid")))
	app, err := strconv.Atoi(pidText)
	if err != nil {
		t.Fatalf("the application's pid file says %q", pidText)
	}
	// Its process group: ExecuteCommand starts it in one of its own.
	var appGone atomic.Bool
	nsswitchtest.KillGroupUnless(t, app, appGone.Load)

	if got := nsswitchtest.Read(filepath.Join(dir, "seen")); got != fedoraView {
		t.Errorf("the application saw\n%q\nwant the view\n%q", got, fedoraView)
	}
	if got, want := nsswitchtest.Read(filepath.Join(dir, "passwd")), nsswitchtest.Read("/etc/passwd"); got != want {
		t.Errorf("the application saw /etc/passwd as %q, want the host's %q", got, want)
	}
	appSees := func(when string) {
		t.Helper()
		if got := nsswitchtest.ReadIn(app, nsswitchtest.Path); got != fedoraView {
			t.Errorf("%s, the application sees\n%q\nwant the view\n%q", when, got, fedoraView)
		}
	}
	appSees("while it runs")
	hostIsAsItWas("while the application runs")

	kill := func(who string, pid int) {
		t.Helper()
		if err := syscall.Kill(pid, syscall.SIGKILL); err != nil {
			t.Fatalf("SIGKILL the %s: %v", who, err)
		}
	}
	switch killFirst {
	case "keploy":
		kill("keploy", keploy.Cmd.Process.Pid)
		keploy.Exited(t)
		if nsswitchtest.Gone(app) {
			t.Fatal("the application did not outlive keploy's SIGKILL")
		}
		appSees("once keploy is killed")
		hostIsAsItWas("once keploy is killed")
		kill("application", app)
		appGone.Store(true) // Reap reaps it; a cleanup runs only once the test has returned
		nsswitchtest.Reap(t, app)
	case "app":
		kill("application", app)
		appGone.Store(true) // keploy's ExecuteCommand reaps it, whenever it does
		keploy.Exited(t)
		if keploy.Err != nil {
			t.Fatalf("keploy's part failed (%v):\n%s", keploy.Err, keploy.Output())
		}
		if got := nsswitchtest.Read(filepath.Join(dir, "returned")); !strings.Contains(got, "signal: killed") {
			t.Errorf("ExecuteCommand returned %q for an application killed with SIGKILL", got)
		}
	}
	hostIsAsItWas("once the application is killed")
}

// Only the application keploy runs natively gets a view: a docker command
// (whose application's container has an /etc of its own) and a script the
// replay runs (no kind) see the host's file as it is.
func TestOnlyANativeAppGetsAViewOfNsswitchConf(t *testing.T) {
	nsswitchtest.Host(t, []byte(fedoraHosts), func(t *testing.T) {
		for _, tc := range []struct {
			kind CmdType
			want string
		}{
			{Native, fedoraView},
			{DockerRun, fedoraHosts},
			{DockerCompose, fedoraHosts},
			{Empty, fedoraHosts},
		} {
			seen := filepath.Join(t.TempDir(), "seen")
			// A cat, which ends by itself: ExecuteCommand says no pid to
			// kill a group of.
			cancel := func(cmd *exec.Cmd) func() error { return func() error { return cmd.Process.Kill() } }
			got := ExecuteCommand(context.Background(), zap.NewNop(), "cat "+nsswitchtest.Path+" > "+seen, tc.kind, cancel, time.Second, nil, nil)
			if got.Err != nil {
				t.Fatalf("kind %q: ExecuteCommand: %v", tc.kind, got.Err)
			}
			if s := nsswitchtest.Read(seen); s != tc.want {
				t.Errorf("a command of kind %q saw\n%q\nwant\n%q", tc.kind, s, tc.want)
			}
		}
		if got := nsswitchtest.Read(nsswitchtest.Path); got != fedoraHosts {
			t.Errorf("the host's %s is %q, want it as it was", nsswitchtest.Path, got)
		}
	})
}

// nobody is the user keploy's part runs as in the file capability's test.
const nobody = 65534

// keploy run as a user, with the remedy its fallback names (the keploy binary
// given CAP_SYS_ADMIN with setcap), makes the application's view, and gives
// the application nothing more: it runs as keploy's user, with no
// capability; its environment is the one keploy was started with, as keploy
// has changed it since, although a file capability starts keploy in secure
// mode, where glibc's loader (keploy's release binary is linked dynamically,
// as this test binary is) removes TMPDIR, LD_LIBRARY_PATH, LOCALDOMAIN and
// the like from keploy's, and Go's runtime may set GOTRACEBACK=none (a
// statically linked binary's does); and its view, which is that user's (with
// no CAP_CHOWN keploy cannot give it to root), is read-only to it. The
// host's file stays as it was.
//
// As root, on a host of the test's own (nsswitchtest), with keploy's part
// played by a copy of this test binary given the file capability, run as
// nobody, in role "capkeploy": ExecuteCommand, as App.Run calls it.
func TestAKeployGivenOnlyCapSysAdminGivesTheAppItsViewAndNothingMore(t *testing.T) {
	if nsswitchtest.Role() == "capkeploy" {
		runAppAsCapKeploy(t)
		return
	}
	nsswitchtest.Host(t, []byte(fedoraHosts), judgeCapKeploy)
}

// runAppAsCapKeploy is keploy's part: it starts the application as App.Run
// does, and the application says, in DIR, what it sees and is.
func runAppAsCapKeploy(t *testing.T) {
	// The exec of a binary with a file capability clears the parent-death
	// signal Command set: set again, and the host checked to be there still.
	if err := unix.Prctl(unix.PR_SET_PDEATHSIG, uintptr(syscall.SIGKILL), 0, 0, 0); err != nil {
		t.Fatal(err)
	}
	if strconv.Itoa(os.Getppid()) != os.Getenv("HOST_PID") {
		t.Fatal("the host is gone")
	}
	dir := os.Getenv("DIR")
	status := nsswitchtest.Read("/proc/self/status")
	// cap_sys_admin+p: permitted, and not effective until keploy raises it,
	// on the thread that makes the view alone.
	if prm, eff := capMask(t, status, "CapPrm"), capMask(t, status, "CapEff"); os.Geteuid() != nobody || prm&(1<<unix.CAP_SYS_ADMIN) == 0 || eff != 0 {
		t.Fatalf("keploy's part runs as uid %d, with %#x permitted and %#x effective: want uid %d with CAP_SYS_ADMIN permitted (the file capability) and nothing effective", os.Geteuid(), prm, eff, nobody)
	}
	// Started in secure mode, with its environment changed before its code
	// ran (else the test proves nothing of the application's): linked
	// dynamically, glibc's loader removed what the host gave (and Go's
	// runtime, which then misses the auxiliary vector, set no GOTRACEBACK);
	// linked statically, the runtime set GOTRACEBACK=none.
	if dynamicallyLinked(t) {
		for _, name := range loaderRemoves {
			if v, ok := os.LookupEnv(name); ok {
				t.Fatalf("%s=%s in keploy's part: glibc's loader did not start it in secure mode, so the test would prove nothing of the application's environment", name, v)
			}
		}
	} else if v := os.Getenv("GOTRACEBACK"); v != "none" {
		t.Fatalf("GOTRACEBACK is %q in keploy's part: Go's runtime did not start it in secure mode, so the test would prove nothing of the application's environment", v)
	}
	if launch.start == nil {
		t.Fatal("keploy's part, started in secure mode, did not read its launch environment")
	}
	// keploy's own changes since it started reach the application as they
	// always did: a variable keploy sets, one the loader removed that keploy
	// then sets itself, and one keploy unsets.
	for k, v := range map[string]string{"KEPLOY_LATER": "1", "MALLOC_ARENA_MAX": "4"} {
		if err := os.Setenv(k, v); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Unsetenv("KEPLOY_DROPPED"); err != nil {
		t.Fatal(err)
	}
	app := fmt.Sprintf(`cat %[1]s > %[2]s/seen; grep -E '^(Uid|CapPrm|CapEff):' /proc/self/status > %[2]s/status; `+
		`env | grep -E '^(%[3]s)=' | LC_ALL=C sort > %[2]s/env; `+
		`if echo x 2> %[2]s/write >> %[1]s; then echo written >> %[2]s/write; fi`, nsswitchtest.Path, dir, strings.Join(capEnvNames, "|"))
	core, logs := observer.New(zap.InfoLevel)
	cancel := func(cmd *exec.Cmd) func() error { return func() error { return cmd.Process.Kill() } }
	if got := ExecuteCommand(context.Background(), zap.New(core), app, Native, cancel, time.Second, nil, nil); got.Err != nil {
		t.Fatalf("ExecuteCommand: %v", got.Err)
	}
	for _, e := range logs.All() {
		if strings.Contains(e.Message, "without a view") {
			t.Errorf("keploy with CAP_SYS_ADMIN fell back: %s (%v)", e.Message, e.ContextMap())
		}
	}
}

func judgeCapKeploy(t *testing.T) {
	// A directory nobody can enter and write, on a mount whose file
	// capabilities the kernel honours: a tmpfs of the host's own, mounted
	// without nosuid (the machine's /tmp may be nosuid, as Fedora's and
	// Debian 13's are), in the host's mount namespace alone. The directory
	// under it is one nobody can reach, in /tmp (not $TMPDIR, which may be a
	// directory nobody cannot enter).
	dir, err := os.MkdirTemp("/tmp", "capkeploy-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	if err := unix.Mount("capkeploy", dir, "tmpfs", unix.MS_NODEV, "mode=0777,size=512m"); err != nil {
		t.Fatalf("mount a tmpfs for the copy of the test binary: %v", err)
	}
	t.Cleanup(func() { _ = unix.Unmount(dir, unix.MNT_DETACH) })
	var fs unix.Statfs_t
	if err := unix.Statfs(dir, &fs); err != nil {
		t.Fatal(err)
	}
	if fs.Flags&unix.ST_NOSUID != 0 {
		t.Fatalf("%s is nosuid, where the kernel ignores file capabilities", dir)
	}
	bin := filepath.Join(dir, "keploy.test")
	self, err := os.ReadFile(os.Args[0])
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(bin, self, 0o755); err != nil {
		t.Fatal(err)
	}
	// setcap cap_sys_admin+p: a vfs_cap_data of revision 2, not effective,
	// with CAP_SYS_ADMIN permitted and nothing inheritable.
	capData := make([]byte, 20)
	binary.LittleEndian.PutUint32(capData[0:], 0x02000000)
	binary.LittleEndian.PutUint32(capData[4:], 1<<unix.CAP_SYS_ADMIN)
	if err := unix.Setxattr(bin, "security.capability", capData, 0); err != nil {
		t.Fatalf("give the copy of the test binary CAP_SYS_ADMIN: %v", err)
	}

	cmd := nsswitchtest.Command(t, "capkeploy", "DIR="+dir, "HOST_PID="+strconv.Itoa(os.Getpid()))
	cmd.Path, cmd.Args[0], cmd.Dir = bin, bin, dir
	// Started with no GOTRACEBACK, and with variables glibc's loader removes
	// in secure mode.
	cmd.Env = slices.DeleteFunc(cmd.Env, func(e string) bool {
		name, _, _ := strings.Cut(e, "=")
		return slices.Contains(capEnvNames, name)
	})
	lib := filepath.Join(dir, "lib")
	cmd.Env = append(cmd.Env, "TMPDIR="+dir, "LD_LIBRARY_PATH="+lib, "LOCALDOMAIN=keploy.test", "MALLOC_ARENA_MAX=2", "KEPLOY_DROPPED=1")
	cmd.SysProcAttr.Credential = &syscall.Credential{Uid: nobody, Gid: nobody}
	keploy := nsswitchtest.Start(t, cmd)
	keploy.Exited(t)
	if keploy.Err != nil || !strings.Contains(keploy.Output(), "--- PASS: "+t.Name()) {
		t.Fatalf("keploy's part failed (%v):\n%s", keploy.Err, keploy.Output())
	}

	if got := nsswitchtest.Read(filepath.Join(dir, "seen")); got != fedoraView {
		t.Errorf("the application saw\n%q\nwant the view\n%q", got, fedoraView)
	}
	status := nsswitchtest.Read(filepath.Join(dir, "status"))
	if want := fmt.Sprintf("Uid:\t%[1]d\t%[1]d\t%[1]d\t%[1]d\n", nobody); !strings.Contains(status, want) {
		t.Errorf("the application runs as %q, want keploy's user: %q", status, want)
	}
	if capMask(t, status, "CapPrm") != 0 || capMask(t, status, "CapEff") != 0 {
		t.Errorf("the application has capabilities: %q", status)
	}
	// As keploy was started (no GOTRACEBACK, the loader's removals back),
	// with keploy's own changes since.
	if got, want := nsswitchtest.Read(filepath.Join(dir, "env")), "KEPLOY_LATER=1\nLD_LIBRARY_PATH="+lib+"\nLOCALDOMAIN=keploy.test\nMALLOC_ARENA_MAX=4\nTMPDIR="+dir+"\n"; got != want {
		t.Errorf("the application's environment has\n%s\nwant\n%s(the environment keploy was started with, with keploy's changes since)", got, want)
	}
	if got := nsswitchtest.Read(filepath.Join(dir, "write")); !strings.Contains(got, "Read-only file system") || strings.Contains(got, "written") {
		t.Errorf("the application's write to its view said %q, want it refused: read-only", got)
	}
	if got := nsswitchtest.Read(nsswitchtest.Path); got != fedoraHosts {
		t.Errorf("the host's %s is %q, want it as it was", nsswitchtest.Path, got)
	}
}

// capEnvNames are the variables the file capability's test follows from the
// host to keploy's part to the application, and loaderRemoves those of them
// that glibc's loader removes from a program it starts in secure mode, in
// every glibc version (MALLOC_ARENA_MAX only from 2.39: the test sets it for
// keploy setting it again, whichever glibc it runs on).
var (
	capEnvNames   = []string{"GOTRACEBACK", "TMPDIR", "LD_LIBRARY_PATH", "LOCALDOMAIN", "MALLOC_ARENA_MAX", "KEPLOY_LATER", "KEPLOY_DROPPED"}
	loaderRemoves = []string{"TMPDIR", "LD_LIBRARY_PATH", "LOCALDOMAIN"}
)

// dynamicallyLinked reports whether this test binary has a program
// interpreter (glibc's loader), as keploy's release binary has.
func dynamicallyLinked(t *testing.T) bool {
	t.Helper()
	exe, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	f, err := elf.Open(exe)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	return slices.ContainsFunc(f.Progs, func(p *elf.Prog) bool { return p.Type == elf.PT_INTERP })
}

// capMask is the capability set field (CapEff, CapPrm) of a
// /proc/PID/status.
func capMask(t *testing.T, status, field string) uint64 {
	t.Helper()
	for _, line := range strings.Split(status, "\n") {
		if v, ok := strings.CutPrefix(line, field+":\t"); ok {
			m, err := strconv.ParseUint(strings.TrimSpace(v), 16, 64)
			if err != nil {
				t.Fatalf("%s: %v", line, err)
			}
			return m
		}
	}
	t.Fatalf("no %s in %q", field, status)
	return 0
}
