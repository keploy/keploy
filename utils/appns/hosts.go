// Package appns starts the application keploy runs natively in a mount
// namespace of its own, in which /etc/nsswitch.conf is a copy whose hosts line
// sends the application's name lookups by a way keploy sees (Start). Only the
// application's processes see the copy: the host's file is never written, and
// the copy is gone once the last of them has exited, however keploy ends.
package appns

import (
	"bytes"
	"slices"
	"strings"
)

// The hosts line's rule.
//
// keploy sees an application's DNS where the application sends it: its
// queries to port 53, which keploy's eBPF hooks send to keploy's DNS server,
// recorded in keploy record and answered from the recording in keploy test. A
// module of the hosts line that asks another process to resolve a name, over
// IPC, has that process send the query, if any: it is not the application's,
// and not keploy's to see.
//
// When. A hosts line that names resolve before dns (or names no dns) gets a
// copy. resolve is nss-resolve, which asks systemd-resolved over its varlink
// (or D-Bus) socket for every name; resolved then queries its upstream
// servers from its own process. Fedora, Arch and others list it before dns
// with [!UNAVAIL=return], so dns is never reached while resolved runs, and
// nothing of the application's DNS is recorded or replayed. After dns, it is
// asked only of the names dns did not answer, and dns, which keploy sees, has
// the application's DNS: no copy. resolve is the one module that takes every
// name; the other IPC modules (below) answer names DNS does not hold, so they
// alone are no reason for a copy, and a line that names them but no resolve
// before dns is kept as it is.
//
// What. The copy's hosts line (each such line: of several, glibc versions
// differ on which they read) keeps, in the host's order and with their
// [STATUS=action] items, the modules that answer from this machine alone,
// with no network and no other process:
//
//   - files: /etc/hosts. Put first where the line lacks it, as resolved
//     answers /etc/hosts' names itself.
//   - myhostname: the machine's own hostname, localhost and _gateway, from
//     the kernel (its hostname, and the machine's addresses over netlink).
//     Put in resolve's place where the line lacks it, as resolved answers
//     those names itself.
//   - libvirt and libvirt_guest: libvirt's guests, from the status and lease
//     files of libvirt's dnsmasq.
//
// and dns, put last where the line lacks it. Every other module is left out,
// with its actions: resolve; mdns, mdns4, mdns6, mdns_minimal, mdns4_minimal
// and mdns6_minimal (avahi-daemon, over its socket: .local names);
// mymachines (systemd-machined, over D-Bus: the local containers' names);
// sss (sssd), ldap (nslcd, or an LDAP server), nis and nisplus (ypbind, or a
// NIS server): a directory's host entries; wins (winbindd or nmbd: NetBIOS
// names); and any module not named here, which keploy cannot show to answer
// without the network or another process. So every lookup of the
// application's that this machine does not answer goes to dns, where keploy
// sees it, in keploy record as in keploy test, and the recording holds every
// name the replay is asked.
//
// A host none of whose hosts lines names resolve before dns gets no copy:
// the file missing (glibc's default, dns then files) and musl (which reads no
// nsswitch.conf) among them.

// takesDNS is the module that takes the application's DNS (above).
const takesDNS = "resolve"

// localOnly are the modules the copy keeps besides dns (above).
var localOnly = []string{"files", "myhostname", "libvirt", "libvirt_guest"}

// earlierRewrite is the hosts line earlier keploy versions wrote over every
// hosts line of the host's /etc/nsswitch.conf (through its link, where it is
// one) while keploy test ran. They put the original back as keploy stopped;
// a run that was killed or crashed did not, and of two runs that overlapped
// the later saved the earlier's rewrite as the original and put that back.
const earlierRewrite = "hosts: files dns"

// authselectHeader begins the nsswitch.conf authselect generates (Fedora's;
// checked on Fedora 44, authselect 1.7.1). Every default profile authselect
// ships writes its hosts line aligned, naming files, myhostname, resolve and
// dns ("hosts:      files myhostname ... resolve [!UNAVAIL=return] dns"),
// never as earlierRewrite.
const authselectHeader = "# Generated by authselect\n"

// leftByEarlierKeploy reports whether conf, the host's nsswitch.conf, is one
// authselect generated whose hosts line is earlierRewrite: a file changed
// since authselect wrote it, to what earlier keploy versions left. Only there
// does the line give that away (and only where authselect still manages the
// file from a default profile it ships: authselectManages): the same line in a file
// authselect did not generate is one anyone may write (Alpine's glibc compat
// ships it, and keploy's own CI lanes write it), and keploy cannot tell it
// from the distribution's own.
func leftByEarlierKeploy(conf []byte) bool {
	if !bytes.HasPrefix(conf, []byte(authselectHeader)) {
		return false
	}
	for _, line := range bytes.Split(conf, []byte("\n")) {
		if string(line) == earlierRewrite {
			return true
		}
	}
	return false
}

// View is what an application is to see of nsswitch.conf.
type View struct {
	// Conf is the copy's bytes.
	Conf []byte
	// From and To are the first hosts line the copy replaces, before and
	// after, as glibc reads it (no comment, single spaces), for log lines.
	From, To string
}

// HostsView returns what an application is to see of nsswitch.conf, whose
// bytes are conf, by the rule above, and whether it differs from conf at all
// (false: no copy). Every line but a replaced hosts line is kept byte for
// byte, its comments and line ending with it; a replaced line keeps what
// comes before its first module ("hosts:" and its spacing), and what comes
// after its last (its comment and line ending).
func HostsView(conf []byte) (View, bool) {
	var v View
	out := make([]byte, 0, len(conf))
	for _, line := range bytes.SplitAfter(conf, []byte("\n")) {
		replaced, services, kept, ok := hostsLineView(string(line))
		if !ok {
			out = append(out, line...)
			continue
		}
		if v.From == "" {
			v.From = "hosts: " + strings.Join(strings.Fields(services), " ")
			v.To = "hosts: " + kept
		}
		out = append(out, replaced...)
	}
	if v.From == "" {
		return View{}, false
	}
	v.Conf = out
	return v, true
}

// hostsLineView returns, when line is a hosts line in which takesDNS comes
// before dns (or that names no dns), line as the copy has it,
// the line's services (its modules and actions), the copy's, and true;
// otherwise false.
func hostsLineView(line string) (replaced, services, kept string, ok bool) {
	prefix, services, rest, ok := splitHostsLine(line)
	if !ok {
		return "", "", "", false
	}
	items, valid := serviceItems(services)
	if !valid {
		return "", "", "", false // glibc reads no such line: nothing to keep from it
	}
	takes := slices.IndexFunc(items, func(it serviceItem) bool { return it.module == takesDNS })
	dnsAt := slices.IndexFunc(items, func(it serviceItem) bool { return it.module == "dns" })
	if takes < 0 || (dnsAt >= 0 && dnsAt < takes) {
		return "", "", "", false
	}
	has := func(module string) bool {
		return slices.ContainsFunc(items, func(it serviceItem) bool { return it.module == module })
	}
	var out []string
	if !has("files") {
		out = append(out, "files")
	}
	for i, it := range items {
		switch {
		case it.module == takesDNS:
			if i == takes && !has("myhostname") {
				out = append(out, "myhostname")
			}
		case it.module == "dns" || slices.Contains(localOnly, it.module):
			out = append(out, it.text)
		}
		// Any other module is left out, with its actions.
	}
	if dnsAt < 0 {
		out = append(out, "dns")
	}
	kept = strings.Join(out, " ")
	return prefix + kept + rest, services, kept, true
}

// splitHostsLine splits a hosts line, as glibc parses one, into what comes
// before its first module (its leading blanks, "hosts", and the blanks and
// colon after it), its modules and actions, and the rest (a comment, the
// blanks before it, and the line ending); ok is false for any other line.
// glibc ends a line at its first '#', skips leading blanks, takes the
// database's name up to a blank or ':', and then skips every blank and colon
// before the first module (so "hosts:files", "hosts : files" and "hosts
// files" all name the hosts database).
func splitHostsLine(line string) (prefix, services, rest string, ok bool) {
	body, end := line, ""
	if i := strings.IndexByte(body, '#'); i >= 0 {
		body, end = body[:i], body[i:]
	} else if i := strings.IndexAny(body, "\r\n"); i >= 0 {
		body, end = body[:i], body[i:]
	}
	// The blanks before the comment or line end belong to the rest, so that
	// a replaced line keeps them.
	trimmed := strings.TrimRight(body, " \t\r\n\v\f")
	end = body[len(trimmed):] + end
	body = trimmed

	i := len(body) - len(strings.TrimLeft(body, " \t\v\f\r"))
	j := i
	for j < len(body) && !isBlank(body[j]) && body[j] != ':' {
		j++
	}
	if body[i:j] != "hosts" || j == len(body) {
		return "", "", "", false
	}
	k := j
	for k < len(body) && (isBlank(body[k]) || body[k] == ':') {
		k++
	}
	return body[:k], body[k:], end, true
}

// serviceItem is a module of a hosts line and the action items after it.
type serviceItem struct {
	module string
	// text is the module and its actions as the copy writes them: the module,
	// then each action as the line has it, a blank between each.
	text string
}

// serviceItems returns the modules of a hosts line's services, each with its
// actions, as glibc reads them, and false where glibc rejects the line: a
// name ends at a blank or '[', and an action item runs from '[' to the next
// ']' and belongs to the module before it. glibc reads no further than an
// action where a module's name is due (first on the line, or after another
// action), and rejects a line with an action never closed or one that is not
// a list of [!]STATUS=ACTION (validAction). A line glibc rejects, or reads
// differently by its version, gets no copy: the application reads it as the
// host does.
func serviceItems(services string) ([]serviceItem, bool) {
	var items []serviceItem
	afterModule := false
	for i := 0; i < len(services); {
		switch c := services[i]; {
		case isBlank(c):
			i++
		case c == '[':
			if !afterModule {
				return items, true
			}
			end := strings.IndexByte(services[i:], ']')
			if end < 0 || !validAction(services[i+1:i+end]) {
				return nil, false
			}
			items[len(items)-1].text += " " + services[i:i+end+1]
			afterModule = false
			i += end + 1
		default:
			j := i
			for j < len(services) && !isBlank(services[j]) && services[j] != '[' {
				j++
			}
			items = append(items, serviceItem{module: services[i:j], text: services[i:j]})
			afterModule = true
			i = j
		}
	}
	return items, true
}

// validAction reports whether the inside of an action item is what glibc
// reads one as: one or more [!]STATUS=ACTION, blanks between them and around
// the '=' (none after the '!'), its words in any case.
func validAction(s string) bool {
	statuses := []string{"success", "notfound", "unavail", "tryagain"}
	actions := []string{"return", "continue", "merge"}
	f := strings.Fields(strings.ReplaceAll(strings.ToLower(s), "=", " = "))
	if len(f) == 0 {
		return false
	}
	for i := 0; i < len(f); i += 3 {
		if !slices.Contains(statuses, strings.TrimPrefix(f[i], "!")) || i+2 >= len(f) || f[i+1] != "=" || !slices.Contains(actions, f[i+2]) {
			return false
		}
	}
	return true
}

func isBlank(c byte) bool {
	switch c {
	case ' ', '\t', '\v', '\f', '\r', '\n':
		return true
	}
	return false
}
