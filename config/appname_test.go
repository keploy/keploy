// WithAppName puts appName in a keploy.yml that names no app with one line,
// and keeps every other byte of it; a file it cannot do that to is refused.
func TestWithAppName(t *testing.T) {
	k := " " + KeptAppNameNote
	for _, c := range []struct{ name, app, doc, want string }{
		{"before the first key", "shop", "path: ./keploy\ncommand: ./app\n", "appName: \"shop\"" + k + "\npath: ./keploy\ncommand: ./app\n"},
		{"header comments stay first", "shop", "# Generated by Keploy\n\npath: x\n", "# Generated by Keploy\n\nappName: \"shop\"" + k + "\npath: x\n"},
		{"after a document start", "shop", "---\npath: x\n", "---\nappName: \"shop\"" + k + "\npath: x\n"},
		{"an indented mapping", "shop", "  path: x\n  command: y\n", "  appName: \"shop\"" + k + "\n  path: x\n  command: y\n"},
		{"CRLF line endings", "shop", "path: x\r\ncommand: y\r\n", "appName: \"shop\"" + k + "\r\npath: x\r\ncommand: y\r\n"},
		{"a last line with no newline", "shop", "path: x", "appName: \"shop\"" + k + "\npath: x"},
		{"an empty file", "shop", "", "appName: \"shop\"" + k + "\n"},
		{"comments only, no final newline", "shop", "# nothing yet", "# nothing yet\nappName: \"shop\"" + k + "\n"},
		{"comments only, CRLF", "shop", "# a\r\n# b\r\n", "# a\r\n# b\r\nappName: \"shop\"" + k + "\r\n"},
		{"appName \"\" of an older keploy", "shop", "path: x\nappName: \"\"\ncommand: y\n", "path: x\nappName: \"shop\"" + k + "\ncommand: y\n"},
		{"appName with no value keeps its comment", "shop", "appName:   # set me\npath: x\n", "appName: \"shop\"" + k + " # set me\npath: x\n"},
		{"appName null", "a", "appName: null\n", "appName: \"a\"" + k + "\n"},
		{"appName Null", "a", "appName: Null\npath: x\n", "appName: \"a\"" + k + "\npath: x\n"},
		{"appName of spaces", "shop", "path: x\nappName: \"  \"\n", "path: x\nappName: \"shop\"" + k + "\n"},
		{"appName of a tab, double-quoted", "shop", "appName: \"\t\"\npath: x\n", "appName: \"shop\"" + k + "\npath: x\n"},
		{"appName of a tab and a space, single-quoted, with a comment", "shop", "appName: '\t ' # blank\npath: x\n", "appName: \"shop\"" + k + " # blank\npath: x\n"},
		{"a key in another case, CRLF", "shop", "appname: ~\r\npath: x\r\n", "appname: \"shop\"" + k + "\r\npath: x\r\n"},
		{"a quoted key", "shop", "'appName': ''\npath: x\n", "'appName': \"shop\"" + k + "\npath: x\n"},
		{"the last line, with no newline", "shop", "path: x\nappName: \"\"", "path: x\nappName: \"shop\"" + k},
		{"a number stays a string", "123", "path: x\n", "appName: \"123\"" + k + "\npath: x\n"},
		{"true stays a string", "true", "path: x\n", "appName: \"true\"" + k + "\npath: x\n"},
		{"null stays a string", "null", "path: x\n", "appName: \"null\"" + k + "\npath: x\n"},
		{"a colon, a space and a #", "my app: v2 #1", "path: x\n", "appName: \"my app: v2 #1\"" + k + "\npath: x\n"},
		{"a later document is not read", "shop", "path: x\n---\nappName: y\n", "appName: \"shop\"" + k + "\npath: x\n---\nappName: y\n"},
	} {
		t.Run(c.name, func(t *testing.T) {
			got, err := WithAppName([]byte(c.doc), c.app)
			if err != nil {
				t.Fatalf("WithAppName(%q): %v", c.doc, err)
			}
			if string(got) != c.want {
				t.Errorf("WithAppName(%q) =\n%q\nwant\n%q", c.doc, got, c.want)
			}
		})
	}
}

// The line WithAppName writes, added or in place of one naming no app, holds
// the name as YAML reads it, and KeptAppNameNote starts the value's line
// comment, a comment the line had kept after it.
func TestWithAppNameNotesKeployKeptTheName(t *testing.T) {
	for _, c := range []struct{ name, doc, comment string }{
		{"a line added", "# mine\npath: x\n", KeptAppNameNote},
		{"a line replaced, its comment kept", "path: x\nappName: ~ # set me\n", KeptAppNameNote + " # set me"},
	} {
		t.Run(c.name, func(t *testing.T) {
			got, err := WithAppName([]byte(c.doc), "shop")
			if err != nil {
				t.Fatalf("WithAppName: %v", err)
			}
			var root yamlLib.Node
			if err := yamlLib.Unmarshal(got, &root); err != nil {
				t.Fatalf("read %q: %v", got, err)
			}
			m := root.Content[0]
			for i := 0; i < len(m.Content); i += 2 {
				if m.Content[i].Value == "appName" {
					if v := m.Content[i+1]; v.Value != "shop" || v.LineComment != c.comment {
						t.Errorf("appName = %q with line comment %q, want \"shop\" with %q", v.Value, v.LineComment, c.comment)
					}
					return
				}
			}
			t.Errorf("%q has no appName key", got)
		})
	}
}

func TestWithAppNameRefuses(t *testing.T) {
	for _, c := range []struct{ name, doc, says string }{
		{"names an app already", "appName: orders\n", "its line 1 is not an appName line"},
		{"names an app between spaces", "appName: \" orders \"\n", "its line 1 is not an appName line"},
		{"names an app in single quotes", "appName: 'orders'\n", "its line 1 is not an appName line"},
		{"names an app between spaces in single quotes", "appName: ' orders '\n", "its line 1 is not an appName line"},
		{"a blank name written as an escape", "appName: \"\\t\"\n", "its line 1 is not an appName line"},
		{"two appName keys", "appName: \"\"\nAPPNAME: \"\"\n", "it has more than one appName key"},
		{"a list", "- a\n", "it is not a mapping of keys"},
		{"an empty flow mapping", "{}\n", "with appName added it would"},
		{"a flow mapping", "{path: x}\n", "with appName added it would not read as YAML"},
		{"a value on the next line", "appName:\n  \"\"\npath: x\n", "with appName added it would not read as YAML"},
		{"a tagged value", "appName: !!str \"\"\npath: x\n", "its line 1 is not an appName line"},
		{"a mapping that starts on the document start line", "--- {path: x}\n", "with appName added it would read as other settings"},
		{"a null document", "~\n", "with appName added it would not read as YAML"},
		{"a key twice", "path: x\npath: y\n", "it does not read as settings"},
		{"not YAML", "path: [\n", "yaml: line "},
	} {
		t.Run(c.name, func(t *testing.T) {
			got, err := WithAppName([]byte(c.doc), "shop")
			if err == nil {
				t.Fatalf("WithAppName(%q) = %q, want a refusal", c.doc, got)
			}
			if !strings.HasPrefix(err.Error(), c.says) {
				t.Errorf("WithAppName(%q) refused with %q, want it to start %q", c.doc, err, c.says)
			}
		})
	}
}
